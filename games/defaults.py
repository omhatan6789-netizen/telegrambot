# ==================================================
# تجهيز الأسئلة الافتراضية لقاعدة البيانات
# ==================================================

def get_default_questions():
    result = []

    # لعبة كلمات
    for word in WORDS:
        result.append({
            "game": "كلمات",
            "question": f"• اكتب كلمة ~ {word}",
            "image": None,
            "caption": None,
            "answers": [word],
        })

    # لعبة تفكيك
    for word in DECOMPOSITION_WORDS:
        result.append({
            "game": "تفكيك",
            "question": f"• فكك كلمة ~ {word}",
            "image": None,
            "caption": None,
            "answers": [" ".join(word)],
        })

    # لعبة الأنمي: استخدام الأسئلة الأصلية دون تغييرها
    for item in ANIME_QUESTIONS:
        result.append({
            "game": "انمي",
            "question": f"• {item['question']}",
            "image": None,
            "caption": None,
            "answers": item["answers"],
        })

    # صور وشخصيات انمي تبدأ فارغة
    return result
