active_games = {}


# =====================
# بدء اللعبة
# =====================

async def start_speed_words(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    if not update.message:
        return


    chat_id = update.effective_chat.id

    word = random.choice(speed_words)


    active_games[chat_id] = word


    await update.message.reply_text(
        f"اكتب الكلمة الي تحت بسرعة!\n\n"
        f" {word}\n\n"
        f" اول واحد يجاوب ياخذ 5 نقاط!⏰"
    )



# =====================
# استقبال الإجابات
# =====================

async def check_speed_words(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    if not update.message:
        return


    chat_id = update.effective_chat.id


    if chat_id not in active_games:
        return


    answer = update.message.text


    if answer == active_games[chat_id]:

        user_id = update.effective_user.id


        add_points(
            user_id,
            5
        )


        await update.message.reply_text(
            f" ☑️ صح عليك {update.effective_user.first_name}!\n"
            f" جاوبت اول واحد وخذيت 5 نقاط👌🏻"
        )


        del active_games[chat_id]