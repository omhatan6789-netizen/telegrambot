def get_games():
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT name
            FROM games
            WHERE status = 'on'
            ORDER BY name
        """)

        return [row[0] for row in cur.fetchall()]

    finally:
        cur.close()
        conn.close()


def get_game_questions(game_name):
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT id, question, image, caption, answers
            FROM game_questions
            WHERE game_name = ?
            ORDER BY id
        """, (game_name,))

        rows = cur.fetchall()
        result = []

        for row in rows:
            try:
                answers = json.loads(row[4] or "[]")
            except (TypeError, ValueError):
                answers = []

            if isinstance(answers, str):
                answers = [answers]

            result.append({
                "id": row[0],
                "question": row[1] or "",
                "image": row[2],
                "caption": row[3],
                "answers": answers,
            })

        return result

    finally:
        cur.close()
        conn.close()


