async def start_game(message, game_name, context):
    chat_id = message.chat_id

    matched_game = get_matching_game(game_name)

    if not matched_game:
        return False

    # إلغاء السؤال السابق من اللعبة نفسها فقط.
    cancel_active_game(chat_id, matched_game)

    # الأسئلة موجودة في الذاكرة؛ لا ننتظر اتصال قاعدة البيانات عند بدء اللعبة.
    questions = get_game_questions(matched_game)

    if not questions:
        await message.reply_text(
            f"ما فيه أسئلة في لعبة {matched_game} حاليًا."
        )
        return True

    valid_questions = [
        question
        for question in questions
        if question["answers"]
        and any(str(answer).strip() for answer in question["answers"])
    ]

    if not valid_questions:
        await message.reply_text(
            "هذه اللعبة لا تحتوي على أسئلة بإجابات صحيحة."
        )
        return True

    question = random.choice(valid_questions)

    answers = [
        answer for answer in question["answers"]
        if str(answer).strip()
    ]

    started_at = time.time()
    display_text = question["question"]

    if matched_game == "صور":
        display_text = "• وش الي بالصورة ؟"

    elif matched_game == "شخصيات انمي":
        display_text = "• من الشخصية الي بالصورة ؟"

    elif matched_game in ("كلمات", "تفكيك", "انمي"):
        display_text = display_text.strip()

        if not display_text.startswith("•"):
            display_text = f"• {display_text}"

    key = get_game_key(chat_id, matched_game)

    active_games[key] = {
        "question_id": question["id"],
        "game": matched_game,
        "answers": answers,
        "started_at": started_at,
        "expires_at": started_at + QUESTION_TIMEOUT,
        "winner": None,
    }

    try:
        if question["image"]:

            # كابشن ثابت مهما كان كابشن الصورة عند الإضافة.
            if matched_game == "صور":
                caption = "• وش الي بالصورة ؟"

            elif matched_game == "شخصيات انمي":
                caption = "• من الشخصية الي بالصورة ؟"

            else:
                caption = question["caption"] or display_text or None

            sent = await message.reply_photo(
                photo=question["image"],
                caption=caption
            )

        else:
            sent = await message.reply_text(display_text)

        # ربط رسالة السؤال برقم السؤال حتى يمكن حذفه بالرد.
        conn = connect()
        cur = conn.cursor()

        try:
            cur.execute("""
                INSERT INTO game_question_messages
                (chat_id, message_id, question_id)
                VALUES (?, ?, ?)
                ON CONFLICT (chat_id, message_id)
                DO UPDATE SET question_id = EXCLUDED.question_id
            """, (
                chat_id,
                sent.message_id,
                question["id"]
            ))

            conn.commit()

        finally:
            cur.close()
            conn.close()

        question_tasks[key] = asyncio.create_task(
            expire_question(
                chat_id,
                matched_game,
                question["id"],
                context
            )
        )

    except Exception:
        cancel_active_game(chat_id, matched_game)
        raise

    return True


