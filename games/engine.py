async def delete_game(message, user_id, game_name):
    if not is_game_admin(user_id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return

    game_name = game_name.strip()

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT name
            FROM games
            WHERE LOWER(name) = LOWER(?)
        """, (game_name,))

        row = cur.fetchone()

        if not row:
            await message.reply_text("اللعبة غير موجودة.")
            return

        actual_name = row[0]

        cur.execute("""
            DELETE FROM game_question_messages
            WHERE question_id IN (
                SELECT id
                FROM game_questions
                WHERE game_name = ?
            )
        """, (actual_name,))

        cur.execute("""
            DELETE FROM game_questions
            WHERE game_name = ?
        """, (actual_name,))

        cur.execute("""
            DELETE FROM games
            WHERE name = ?
        """, (actual_name,))

        conn.commit()

        for chat_id, active in list(active_games.items()):
            if active.get("game") == actual_name:
                active_games.pop(chat_id, None)

        await message.reply_text(
            f"تم حذف لعبة {actual_name} وجميع أسئلتها."
        )

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


