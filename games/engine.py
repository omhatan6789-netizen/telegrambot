async def delete_question_by_reply(message, user_id, game_name):
    if not is_game_admin(user_id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return

    replied = message.reply_to_message

    if not replied:
        await message.reply_text(
            "رد على رسالة السؤال واكتب:\n"
            "حذف اسم اللعبة"
        )
        return

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT question_id
            FROM game_question_messages
            WHERE chat_id = ?
            AND message_id = ?
        """, (
            message.chat_id,
            replied.message_id
        ))

        row = cur.fetchone()

        if not row:
            await message.reply_text(
                "ما لقيت سؤالًا مرتبطًا بالرسالة التي رددت عليها."
            )
            return

        question_id = row[0]

        cur.execute("""
            SELECT game_name
            FROM game_questions
            WHERE id = ?
        """, (question_id,))

        question_row = cur.fetchone()

        if not question_row:
            await message.reply_text("السؤال غير موجود.")
            return

        actual_game = question_row[0]

        if normalize_text(actual_game) != normalize_text(game_name):
            await message.reply_text(
                f"السؤال الذي رددت عليه ليس من لعبة {game_name}."
            )
            return

        cur.execute("""
            DELETE FROM game_question_messages
            WHERE question_id = ?
        """, (question_id,))

        cur.execute("""
            DELETE FROM game_questions
            WHERE id = ?
        """, (question_id,))

        conn.commit()

        # إلغاء السؤال إذا كان هو السؤال النشط في القروب
        active = active_games.get(message.chat_id)

        if active and active.get("question_id") == question_id:
            active_games.pop(message.chat_id, None)

        await message.reply_text("تم حذف السؤال وإجاباته بنجاح.")

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


