def load_game_caches():
    """تحميل الألعاب وأسئلتها إلى الذاكرة عند تشغيل البوت."""
    global _games_cache, _games_cache_loaded, _questions_cache

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT name
            FROM games
            WHERE status = 'on'
            ORDER BY name
        """)
        games = [row[0] for row in cur.fetchall()]

        cur.execute("""
            SELECT id, game_name, question, image, caption, answers
            FROM game_questions
            ORDER BY id
        """)

        questions = {
            normalize_text(name): []
            for name in games
        }

        for row in cur.fetchall():
            try:
                answers = json.loads(row[5] or "[]")
            except (TypeError, ValueError):
                answers = []

            if isinstance(answers, str):
                answers = [answers]
            elif not isinstance(answers, list):
                answers = []

            key = normalize_text(row[1])
            questions.setdefault(key, []).append({
                "id": row[0],
                "question": row[2] or "",
                "image": row[3],
                "caption": row[4],
                "answers": answers,
            })

        _games_cache = games
        _games_cache_loaded = True
        _questions_cache = questions

    finally:
        cur.close()
        conn.close()


def get_game_questions(game_name, force=False):
    cache_key = normalize_text(game_name)

    if not force and cache_key in _questions_cache:
        return list(_questions_cache[cache_key])

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT id, question, image, caption, answers
            FROM game_questions
            WHERE game_name = ?
            ORDER BY id
        """, (game_name,))

        result = []

        for row in cur.fetchall():
            try:
                answers = json.loads(row[4] or "[]")
            except (TypeError, ValueError):
                answers = []

            if isinstance(answers, str):
                answers = [answers]

            if not isinstance(answers, list):
                answers = []

            result.append({
                "id": row[0],
                "question": row[1] or "",
                "image": row[2],
                "caption": row[3],
                "answers": answers,
            })

        _questions_cache[cache_key] = result
        return list(result)

    finally:
        cur.close()
        conn.close()


