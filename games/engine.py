def normalize_text(value):
    value = str(value or "").strip().lower()
    value = re.sub(r"[\u064B-\u065F\u0670]", "", value)
    value = value.replace("أ", "ا").replace("إ", "ا").replace("آ", "ا")
    value = value.replace("ى", "ي")
    value = re.sub(r"\s+", " ", value)
    return value


def is_game_admin(user_id):
    return user_id == OWNER_ID or is_admin(user_id)


def ensure_game_tables():
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS games (
                name TEXT PRIMARY KEY,
                image TEXT,
                status TEXT DEFAULT 'on'
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS game_questions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                game_name TEXT,
                question TEXT,
                image TEXT,
                caption TEXT,
                answers TEXT
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS game_question_messages (
                chat_id BIGINT NOT NULL,
                message_id BIGINT NOT NULL,
                question_id BIGINT NOT NULL,
                PRIMARY KEY (chat_id, message_id)
            )
        """)

        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_game_question_messages_question
            ON game_question_messages(question_id)
        """)

        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_game_questions_game_name
            ON game_questions(game_name)
        """)

        # إضافة الألعاب الأساسية دون حذف الألعاب الموجودة
        for game_name in DEFAULT_GAMES:
            cur.execute("""
                INSERT INTO games (name, status)
                VALUES (?, 'on')
                ON CONFLICT (name) DO NOTHING
            """, (game_name,))

        # إضافة الأسئلة الافتراضية مرة واحدة لكل لعبة
        defaults = get_default_questions()

        for game_name in DEFAULT_GAMES:
            cur.execute("""
                SELECT COUNT(*)
                FROM game_questions
                WHERE game_name = ?
            """, (game_name,))

            count = cur.fetchone()[0]

            if count:
                continue

            for item in defaults:
                if item["game"] != game_name:
                    continue

                cur.execute("""
                    INSERT INTO game_questions
                    (game_name, question, image, caption, answers)
                    VALUES (?, ?, ?, ?, ?)
                """, (
                    item["game"],
                    item["question"],
                    item.get("image"),
                    item.get("caption"),
                    json.dumps(
                        item["answers"],
                        ensure_ascii=False
                    )
                ))

        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


def get_games():
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT name
            FROM games
            WHERE status = 'on'
            ORDER BY name
        """)
        return [row[0] for row in cur.fetchall()]

    finally:
        cur.close()
        conn.close()


def get_game_questions(game_name):
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT id, question, image, caption, answers
            FROM game_questions
            WHERE game_name = ?
            ORDER BY id
        """, (game_name,))

        rows = cur.fetchall()

        result = []

        for row in rows:
            try:
                answers = json.loads(row[4] or "[]")
            except Exception:
                answers = []

            if isinstance(answers, str):
                answers = [answers]

            result.append({
                "id": row[0],
                "question": row[1] or "",
                "image": row[2],
                "caption": row[3],
                "answers": answers,
            })

        return result

    finally:
        cur.close()
        conn.close()


def get_question_by_id(question_id):
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT id, game_name, question, image, caption, answers
            FROM game_questions
            WHERE id = ?
        """, (question_id,))

        row = cur.fetchone()

        if not row:
            return None

        try:
            answers = json.loads(row[5] or "[]")
        except Exception:
            answers = []

        if isinstance(answers, str):
            answers = [answers]

        return {
            "id": row[0],
            "game": row[1],
            "question": row[2] or "",
            "image": row[3],
            "caption": row[4],
            "answers": answers,
        }

    finally:
        cur.close()
        conn.close()


