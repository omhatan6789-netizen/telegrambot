def get_games(force=False):
    global _games_cache, _games_cache_loaded

    if _games_cache_loaded and not force:
        return list(_games_cache)

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT name
            FROM games
            WHERE status = 'on'
            ORDER BY name
        """)

        _games_cache = [row[0] for row in cur.fetchall()]
        _games_cache_loaded = True
        return list(_games_cache)

    finally:
        cur.close()
        conn.close()


def get_matching_game(game_name):
    normalized = normalize_text(game_name)

    if not normalized:
        return None

    return next(
        (
            name for name in get_games()
            if normalize_text(name) == normalized
        ),
        None
    )


