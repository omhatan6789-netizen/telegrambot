async def check_answer(message):
    chat_id = message.chat_id
    user = message.from_user

    if not user or not message.text:
        return False

    game = active_games.get(chat_id)

    if not game:
        return False

    if time.time() >= game["expires_at"]:
        cancel_active_game(chat_id)
        return False

    if game.get("winner"):
        return False

    text = normalize_text(message.text)

    answers = [
        normalize_text(answer)
        for answer in game["answers"]
        if answer
    ]

    if text not in answers:
        return False

    # تثبيت الفائز قبل إضافة النقاط لمنع فوز شخصين.
    game["winner"] = user.id

    elapsed = max(0, time.time() - game["started_at"])

    if elapsed < 60:
        elapsed_text = f"{elapsed:.2f} ثانية"
    else:
        minutes = int(elapsed // 60)
        seconds = elapsed % 60
        elapsed_text = f"{minutes} دقيقة و {seconds:.2f} ثانية"

    try:
        # استخدام نظام النقاط الأصلي حتى يتحدث الكاش والحفظ المؤجل.
        total_points = add_points(
            user.id,
            POINTS_REWARD
        )

    except Exception:
        cancel_active_game(chat_id)
        raise

    cancel_active_game(chat_id)

    name = html.escape(user.first_name or "لاعب")
    mention = f'<a href="tg://user?id={user.id}">{name}</a>'

    await message.reply_text(
        "• صح عليك!! " + mention + "\n"
        f"• جبتها ب {elapsed_text}\n"
        f"• نقاطك صارت <b>{total_points}</b>",
        parse_mode=ParseMode.HTML
    )

    return True


