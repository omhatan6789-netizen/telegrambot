async def delete_game(message, user_id, game_name):
    global _games_cache, _games_cache_loaded

    if not is_game_admin(user_id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return

    actual_name = get_matching_game(game_name)

    if not actual_name:
        await message.reply_text("اللعبة غير موجودة.")
        return

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            DELETE FROM game_question_messages
            WHERE question_id IN (
                SELECT id
                FROM game_questions
                WHERE game_name = ?
            )
        """, (actual_name,))

        cur.execute("""
            DELETE FROM game_questions
            WHERE game_name = ?
        """, (actual_name,))

        cur.execute("""
            DELETE FROM games
            WHERE name = ?
        """, (actual_name,))

        conn.commit()

        cancel_game_everywhere(actual_name)

        if _games_cache_loaded:
            _games_cache = [
                name for name in _games_cache
                if normalize_text(name) != normalize_text(actual_name)
            ]

        _questions_cache.pop(normalize_text(actual_name), None)

        await message.reply_text(
            f"تم حذف لعبة {actual_name} وجميع أسئلتها."
        )

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


# ==================================================
# حذف سؤال بالرد على رسالته
# ==================================================

async def delete_question_by_reply(message, user_id, game_name):
    if not is_game_admin(user_id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return

    replied = message.reply_to_message

    if not replied:
        await message.reply_text(
            "رد على رسالة السؤال واكتب:\n"
            "حذف اسم اللعبة"
        )
        return

    actual_game = get_matching_game(game_name)

    if not actual_game:
        await message.reply_text("اللعبة غير موجودة.")
        return

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            SELECT question_id
            FROM game_question_messages
            WHERE chat_id = ?
            AND message_id = ?
        """, (
            message.chat_id,
            replied.message_id
        ))

        row = cur.fetchone()

        if not row:
            await message.reply_text(
                "ما لقيت سؤالًا مرتبطًا بالرسالة التي رددت عليها."
            )
            return

        question_id = row[0]

        cur.execute("""
            SELECT game_name
            FROM game_questions
            WHERE id = ?
        """, (question_id,))

        question_row = cur.fetchone()

        if not question_row:
            await message.reply_text("السؤال غير موجود.")
            return

        if normalize_text(question_row[0]) != normalize_text(actual_game):
            await message.reply_text(
                f"السؤال الذي رددت عليه ليس من لعبة {actual_game}."
            )
            return

        cur.execute("""
            DELETE FROM game_question_messages
            WHERE question_id = ?
        """, (question_id,))

        cur.execute("""
            DELETE FROM game_questions
            WHERE id = ?
        """, (question_id,))

        conn.commit()

        cancel_question_everywhere(question_id)

        cache_key = normalize_text(actual_game)
        cached_questions = _questions_cache.get(cache_key)
        if cached_questions is not None:
            _questions_cache[cache_key] = [
                item for item in cached_questions
                if item["id"] != question_id
            ]

        await message.reply_text(
            "تم حذف السؤال وإجاباته بنجاح."
        )

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


# ==================================================
# استقبال رسائل الألعاب
# ==================================================

async def game_message_handler(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):
    message = update.effective_message
    user = update.effective_user
    chat = update.effective_chat

    if not message or not user or not chat:
        return

    if chat.type not in ("group", "supergroup"):
        return

    text = (message.text or "").strip()
    normalized = normalize_text(text)

    # --------------------------------------------------
    # إلغاء جلسات الإضافة
    # --------------------------------------------------

    if normalized == "الغاء":
        removed = False

        game_session = add_game_sessions.get(user.id)

        if game_session and game_session["chat_id"] == chat.id:
            add_game_sessions.pop(user.id, None)
            removed = True

        question_session = add_question_sessions.get(user.id)

        if question_session and question_session["chat_id"] == chat.id:
            add_question_sessions.pop(user.id, None)
            removed = True

        if removed:
            await message.reply_text("تم إلغاء العملية.")
            return

    # --------------------------------------------------
    # استقبال اسم لعبة جديدة
    # --------------------------------------------------

    game_session = add_game_sessions.get(user.id)

    if game_session and game_session["chat_id"] == chat.id:
        if text:
            add_game_sessions.pop(user.id, None)
            await save_new_game(message, text)
            return

    # --------------------------------------------------
    # استقبال سؤال أو إجابات
    # --------------------------------------------------

    question_session = add_question_sessions.get(user.id)

    if question_session and question_session["chat_id"] == chat.id:
        handled = await receive_add_question(
            message,
            question_session
        )

        if handled:
            return

    # --------------------------------------------------
    # أوامر الإدارة
    # --------------------------------------------------

    if not text:
        return

    if normalized == "اضف لعبة":
        await begin_add_game(message, user.id)
        return

    if normalized.startswith("اضف لعبة "):
        name = text[len("اضف لعبة "):].strip()
        await save_new_game(message, name)
        return

    if normalized.startswith("حذف لعبة "):
        name = text[len("حذف لعبة "):].strip()
        await delete_game(message, user.id, name)
        return

    if normalized.startswith("حذف ") and message.reply_to_message:
        name = text[len("حذف "):].strip()
        await delete_question_by_reply(message, user.id, name)
        return

    if normalized.startswith("اضف "):
        game_name = text[len("اضف "):].strip()

        if normalize_text(game_name) != "لعبة":
            await begin_add_question(message, user.id, game_name)

        return

    # --------------------------------------------------
    # عرض الألعاب
    # --------------------------------------------------

    if normalized in ("الالعاب", "العاب"):
        games = get_games()

        if not games:
            await message.reply_text("ما فيه ألعاب حاليًا.")
            return

        # جلب أعداد الأسئلة باستعلام واحد بدل استعلام لكل لعبة.
        conn = connect()
        cur = conn.cursor()

        try:
            cur.execute("""
                SELECT game_name, COUNT(*)
                FROM game_questions
                GROUP BY game_name
            """)

            counts = {
                row[0]: row[1]
                for row in cur.fetchall()
            }

        finally:
            cur.close()
            conn.close()

        lines = ["الألعاب المتوفرة:"]

        for game_name in games:
            questions_count = counts.get(game_name, 0)
            lines.append(
                f"• {game_name} — {questions_count} سؤال"
            )

        await message.reply_text("\n".join(lines))
        return

    # --------------------------------------------------
    # فحص الإجابات في جميع الألعاب النشطة
    # --------------------------------------------------

    if await check_answer(message):
        return

    # --------------------------------------------------
    # تشغيل لعبة بالاسم
    # --------------------------------------------------

    matched_game = get_matching_game(text)

    if matched_game:
        await start_game(
            message,
            matched_game,
            context
        )
