OWNER_ID = 8453977662
QUESTION_TIMEOUT = 300
POINTS_REWARD = 3

# جلسة السؤال النشط مستقلة لكل قروب
active_games = {}

# جلسات إضافة لعبة أو سؤال
add_game_sessions = {}
