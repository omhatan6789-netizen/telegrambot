async def check_answer(message):
    chat_id = message.chat_id
    user = message.from_user

    if not user or not message.text:
        return False

    game = active_games.get(chat_id)

    if not game:
        return False

    if time.time() >= game["expires_at"]:
        active_games.pop(chat_id, None)
        return False

    text = normalize_text(message.text)

    answers = [
        normalize_text(answer)
        for answer in game["answers"]
        if answer
    ]

    if text not in answers:
        return False

    # منع فوز أكثر من شخص
    if game.get("winner"):
        return False

    game["winner"] = user.id

    elapsed = max(0, time.time() - game["started_at"])

    if elapsed < 60:
        elapsed_text = f"{elapsed:.2f} ثانية"
    else:
        minutes = int(elapsed // 60)
        seconds = elapsed % 60
        elapsed_text = f"{minutes} دقيقة و {seconds:.2f} ثانية"

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            INSERT INTO points (user_id, points)
            VALUES (?, ?)
            ON CONFLICT (user_id)
            DO UPDATE SET points = points.points + EXCLUDED.points
            RETURNING points
        """, (user.id, POINTS_REWARD))

        total_points = cur.fetchone()[0]
        conn.commit()

    except Exception:
        conn.rollback()
        active_games.pop(chat_id, None)
        raise

    finally:
        cur.close()
        conn.close()

    active_games.pop(chat_id, None)

    name = html.escape(user.first_name or "لاعب")

    mention = (
        f'<a href="tg://user?id={user.id}">{name}</a>'
    )

    await message.reply_text(
        "• صح عليك!! " + mention + "\n"
        f"• جبتها ب {elapsed_text}\n"
        f"• نقاطك صارت <b>{total_points}</b>",
        parse_mode=ParseMode.HTML
    )

    return True


