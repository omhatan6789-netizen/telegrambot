async def save_new_game(message, name):
    if not is_game_admin(message.from_user.id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return

    name = name.strip()

    if not name:
        await message.reply_text("اسم اللعبة غير صحيح.")
        return

    if len(name) > 40:
        await message.reply_text("اسم اللعبة طويل جدًا.")
        return

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            INSERT INTO games (name, status)
            VALUES (?, 'on')
            ON CONFLICT (name) DO NOTHING
            RETURNING name
        """, (name,))

        created = cur.fetchone()
        conn.commit()

        if created:
            if _games_cache_loaded:
                _games_cache.append(name)
                _games_cache.sort()
            else:
                invalidate_games_cache()

            _questions_cache[normalize_text(name)] = []

            await message.reply_text(
                f"تمت إضافة لعبة {name} بنجاح.\n"
                "اللعبة أُنشئت فارغة، ويمكنك إضافة الأسئلة لها."
            )
        else:
            await message.reply_text("هذه اللعبة موجودة بالفعل.")

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


