def ensure_game_tables():
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            CREATE TABLE IF NOT EXISTS games (
                name TEXT PRIMARY KEY,
                image TEXT,
                status TEXT DEFAULT 'on'
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS game_questions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                game_name TEXT,
                question TEXT,
                image TEXT,
                caption TEXT,
                answers TEXT
            )
        """)

        # إصلاح الترقيم التلقائي للأسئلة القديمة.
        cur.execute("""
            CREATE SEQUENCE IF NOT EXISTS game_questions_id_seq
        """)

        cur.execute("""
            ALTER TABLE game_questions
            ALTER COLUMN id
            SET DEFAULT nextval('game_questions_id_seq')
        """)

        cur.execute("""
            SELECT setval(
                'game_questions_id_seq',
                GREATEST(COALESCE(MAX(id), 0) + 1, 1),
                false
            )
            FROM game_questions
        """)

        cur.execute("""
            ALTER SEQUENCE game_questions_id_seq
            OWNED BY game_questions.id
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS game_question_messages (
                chat_id BIGINT NOT NULL,
                message_id BIGINT NOT NULL,
                question_id BIGINT NOT NULL,
                PRIMARY KEY (chat_id, message_id)
            )
        """)

        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_game_question_messages_question
            ON game_question_messages(question_id)
        """)

        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_game_questions_game_name
            ON game_questions(game_name)
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS game_engine_migrations (
                migration_name TEXT PRIMARY KEY,
                completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # حذف بيانات نظام الألعاب القديم مرة واحدة فقط.
        cur.execute("""
            SELECT migration_name
            FROM game_engine_migrations
            WHERE migration_name = ?
        """, ("remove_old_games_system_v1",))

        migration_done = cur.fetchone()

        if not migration_done:
            cur.execute("DELETE FROM game_question_messages")
            cur.execute("DELETE FROM game_questions")
            cur.execute("DELETE FROM games")

            cur.execute("""
                INSERT INTO game_engine_migrations (migration_name)
                VALUES (?)
                ON CONFLICT (migration_name) DO NOTHING
            """, ("remove_old_games_system_v1",))

        # إنشاء الألعاب الأساسية.
        for game_name in DEFAULT_GAMES:
            cur.execute("""
                INSERT INTO games (name, status)
                VALUES (?, 'on')
                ON CONFLICT (name) DO NOTHING
            """, (game_name,))

        # إضافة الأسئلة الافتراضية إذا كانت اللعبة فارغة.
        defaults = get_default_questions()

        for game_name in DEFAULT_GAMES:
            cur.execute("""
                SELECT COUNT(*)
                FROM game_questions
                WHERE game_name = ?
            """, (game_name,))

            count = cur.fetchone()[0]

            if count:
                continue

            for item in defaults:
                if item["game"] != game_name:
                    continue

                cur.execute("""
                    INSERT INTO game_questions
                    (game_name, question, image, caption, answers)
                    VALUES (?, ?, ?, ?, ?)
                """, (
                    item["game"],
                    item["question"],
                    item.get("image"),
                    item.get("caption"),
                    json.dumps(
                        item["answers"],
                        ensure_ascii=False
                    )
                ))

        conn.commit()
        invalidate_games_cache()
        invalidate_questions_cache()

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()

    # تحميل أسماء الألعاب والأسئلة مرة واحدة عند بدء تشغيل البوت.
    load_game_caches()


