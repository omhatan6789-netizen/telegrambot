async def check_answer(message):
    chat_id = message.chat_id
    user = message.from_user

    if not user or not message.text:
        return False

    text = normalize_text(message.text)

    if not text:
        return False

    # البحث عن اللعبة التي تطابق إجابتها الرسالة.
    # إذا تطابقت الإجابة مع أكثر من لعبة، نعتمد السؤال الأحدث.
    matching_games = []

    for key, game in list(active_games.items()):
        if key[0] != chat_id:
            continue

        if time.time() >= game["expires_at"]:
            continue

        if game.get("winner"):
            continue

        answers = [
            normalize_text(answer)
            for answer in game["answers"]
            if answer
        ]

        if text in answers:
            matching_games.append((key, game))

    if not matching_games:
        return False

    key, game = max(
        matching_games,
        key=lambda item: item[1]["started_at"]
    )

    # تثبيت الفائز قبل إضافة النقاط.
    game["winner"] = user.id

    elapsed = max(0, time.time() - game["started_at"])

    if elapsed < 60:
        elapsed_text = f"{elapsed:.2f} ثانية"
    else:
        minutes = int(elapsed // 60)
        seconds = elapsed % 60
        elapsed_text = f"{minutes} دقيقة و {seconds:.2f} ثانية"

    try:
        total_points = add_points(
            user.id,
            POINTS_REWARD
        )

    except Exception:
        cancel_active_game(chat_id, game["game"])
        raise

    # إنهاء اللعبة التي تمت الإجابة عليها فقط.
    cancel_active_game(chat_id, game["game"])

    name = html.escape(user.first_name or "لاعب")
    mention = f'<a href="tg://user?id={user.id}">{name}</a>'

    await message.reply_text(
        "• صح عليك!! " + mention + "\n"
        f"• جبتها ب {elapsed_text}\n"
        f"• نقاطك صارت <b>{total_points}</b>",
        parse_mode=ParseMode.HTML
    )

    return True


