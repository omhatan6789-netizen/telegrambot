async def begin_add_question(message, user_id, game_name):
    if not is_game_admin(user_id):
        await message.reply_text("هذا الأمر للمشرفين فقط.")
        return

    games = get_games()

    matched_game = next(
        (
            name for name in games
            if normalize_text(name) == normalize_text(game_name)
        ),
        None
    )

    if not matched_game:
        await message.reply_text(
            "اللعبة غير موجودة.\n"
            "أرسل الالعاب لمعرفة الألعاب المتوفرة."
        )
        return

    add_question_sessions[user_id] = {
        "chat_id": message.chat_id,
        "game": matched_game,
        "stage": "question",
        "question": None,
        "image": None,
        "caption": None,
        "answers": [],
    }

    await message.reply_text(
        f"أرسل محتوى السؤال للعبة {matched_game}.\n"
        "يمكنك إرسال نص أو صورة مع كابشن.\n"
        "أرسل إلغاء لإيقاف العملية."
    )


async def receive_add_question(message, context, session):
    user_id = message.from_user.id

    if message.chat_id != session["chat_id"]:
        return False

    if session["stage"] == "question":
        if message.photo:
            session["image"] = message.photo[-1].file_id
            session["caption"] = message.caption or ""

            if session["game"] in ("صور", "شخصيات انمي"):
                session["question"] = ""
            else:
                session["question"] = message.caption or ""

        elif message.text:
            session["question"] = message.text.strip()

        else:
            await message.reply_text("أرسل نصًا أو صورة.")
            return True

        session["stage"] = "answers"

        await message.reply_text(
            "ممتاز! أرسل الإجابات الآن.\n"
            "تقدر ترسل أكثر من إجابة في رسالة واحدة، "
            "وكل إجابة في سطر مستقل.\n"
            "وبعد الانتهاء أرسل كلمة: تم"
        )

        return True

    if session["stage"] == "answers":
        if not message.text:
            await message.reply_text(
                "أرسل الإجابات كنص، كل إجابة في سطر."
            )
            return True

        text = message.text.strip()

        if normalize_text(text) == "تم":
            answers = list(dict.fromkeys(
                answer.strip()
                for answer in session["answers"]
                if answer.strip()
            ))

            if not answers:
                await message.reply_text(
                    "لم تضف أي إجابة. أرسل الإجابات أولًا."
                )
                return True

            await save_question(message, session, answers)
            add_question_sessions.pop(user_id, None)
            return True

        new_answers = [
            line.strip()
            for line in text.splitlines()
            if line.strip()
        ]

        session["answers"].extend(new_answers)

        await message.reply_text(
            f"تم استلام {len(new_answers)} إجابة.\n"
            "أرسل إجابات إضافية أو اكتب تم للحفظ."
        )

        return True

    return False


async def save_question(message, session, answers):
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            INSERT INTO game_questions
            (game_name, question, image, caption, answers)
            VALUES (?, ?, ?, ?, ?)
        """, (
            session["game"],
            session["question"],
            session["image"],
            session["caption"],
            json.dumps(answers, ensure_ascii=False)
        ))

        conn.commit()

        await message.reply_text(
            f"تمت إضافة السؤال إلى لعبة {session['game']} بنجاح.\n"
            f"عدد الإجابات: {len(answers)}"
        )

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


