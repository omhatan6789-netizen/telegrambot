async def create_async_schema() -> None:
    """Create all tables and indexes in one transaction."""

    async with connection() as conn:
        async with conn.transaction():

            await conn.execute(
                "SELECT pg_advisory_xact_lock(%s)",
                (SCHEMA_LOCK_ID,),
            )

            for statement in SCHEMA_STATEMENTS:
                await conn.execute(statement)

            # Essential owner record only.
            await conn.execute(
                """
                INSERT INTO users (user_id, rank)
                VALUES (%s, 'Dev')
                ON CONFLICT (user_id)
                DO UPDATE SET rank = 'Dev'
                """,
                (OWNER_ID,),
            )

            await conn.execute(
                """
                INSERT INTO developers (user_id, developer_type)
                VALUES (%s, 'primary')
                ON CONFLICT (user_id) DO NOTHING
                """,
                (OWNER_ID,),
            )

            await conn.execute(
                """
                INSERT INTO games_settings (id, status)
                VALUES (1, 'on')
                ON CONFLICT (id) DO NOTHING
                """
            )

            await conn.execute(
                """
                INSERT INTO start_settings (
                    id, message_text, message_entities
                )
                VALUES (1, '', '[]')
                ON CONFLICT (id) DO NOTHING
                """
            )

    logger.info(
        "Async database schema created: %s statements",
        len(SCHEMA_STATEMENTS),
    )
