def ensure_mandatory_subscription_tables():
    conn = connect()
    cur = conn.cursor()

    try:
        acquire_schema_lock(conn)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS mandatory_subscription_settings (
                chat_id BIGINT PRIMARY KEY,
                enabled INTEGER NOT NULL DEFAULT 0,
                updated_by BIGINT,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        cur.execute("""
            CREATE TABLE IF NOT EXISTS mandatory_subscription_requirements (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                group_id BIGINT NOT NULL,
                requirement_type TEXT NOT NULL,
                target_chat_id BIGINT,
                target TEXT NOT NULL,
                title TEXT NOT NULL,
                join_url TEXT NOT NULL,
                UNIQUE(group_id, requirement_type, target)
            )
        """)

        cur.execute("""
            CREATE INDEX IF NOT EXISTS idx_mandatory_subscription_group
            ON mandatory_subscription_requirements(group_id)
        """)

        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


