def _parse_public_telegram_target(value):
    """إرجاع username من @username أو رابط t.me عام."""

    value = value.strip()

    if value.startswith("@"):
        username = value[1:]

        return (
            username
            if re.fullmatch(r"[A-Za-z0-9_]{5,32}", username)
            else None
        )

    if value.startswith(("https://", "http://")):
        parsed = urlparse(value)

        if parsed.netloc.lower() not in {
            "t.me",
            "www.t.me",
            "telegram.me",
            "www.telegram.me",
        }:
            return None

        path = parsed.path.strip("/")

        if not path or path.startswith("+") or path.startswith("joinchat/"):
            return None

        username = path.split("/")[0]

        if username.lower() in {
            "share",
            "proxy",
            "addstickers",
            "iv",
        }:
            return None

        return (
            username
            if re.fullmatch(r"[A-Za-z0-9_]{5,32}", username)
            else None
        )

    return None


def _is_member_status(member):
    status = getattr(member, "status", None)

    if status in ("creator", "administrator", "member"):
        return True

    if status == "restricted":
        return bool(getattr(member, "is_member", False))

    return False


async def _check_chat_membership(context, user_id, target_chat_id):
    """
    فحص العضوية مع كاش قصير للنتائج السلبية،
    وكاش أطول قليلًا للنتائج الإيجابية.
    """
    key = (int(target_chat_id), int(user_id))
    now = time.monotonic()

    cached = _membership_cache.get(key)

    if cached is not None:
        checked_at, is_member = cached

        ttl = (
            MEMBERSHIP_CACHE_TTL
            if is_member
            else NEGATIVE_MEMBERSHIP_CACHE_TTL
        )

        if now - checked_at < ttl:
            return is_member

        _membership_cache.pop(key, None)

    try:
        member = await context.bot.get_chat_member(
            chat_id=int(target_chat_id),
            user_id=int(user_id),
        )

        is_member = _is_member_status(member)

        _membership_cache[key] = (
            time.monotonic(),
            is_member,
        )

        return is_member

    except TelegramError as exc:
        # لا نعتبر الخطأ اشتراكًا صحيحًا.
        # نخزّن النتيجة السلبية مدة قصيرة لتقليل تكرار الطلبات.
        _membership_cache[key] = (
            time.monotonic(),
            False,
        )

        print(
            "⚠️ تعذر التحقق من الاشتراك الإجباري "
            f"في {target_chat_id}: {exc}"
        )

        return False


async def _check_requirement(context, user_id, req):
    # tuple:
    # id, type, target_chat_id, target, title, join_url

    _rid, req_type, target_chat_id, _target, _title, _join_url = req

    if req_type == "start":
        return await asyncio.to_thread(
            _private_start_exists_sync,
            user_id,
        )

    if req_type != "chat" or target_chat_id is None:
        return False

    return await _check_chat_membership(
        context,
        user_id,
        target_chat_id,
    )


def _escape(value):
    return html.escape(str(value or ""), quote=True)


