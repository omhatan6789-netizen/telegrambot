def _db_fetchone(query, params=()):
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute(query, params)
        return cur.fetchone()

    finally:
        cur.close()
        conn.close()


def _db_fetchall(query, params=()):
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute(query, params)
        return cur.fetchall()

    finally:
        cur.close()
        conn.close()


def _is_developer_sync(user_id):
    if not user_id:
        return False

    if user_id == OWNER_ID:
        return True

    conn = None
    cur = None

    try:
        conn = connect()
        cur = conn.cursor()

        cur.execute(
            """
            SELECT 1
            FROM developer_panel_access
            WHERE user_id=?
            LIMIT 1
            """,
            (user_id,),
        )

        return cur.fetchone() is not None

    except Exception:
        return False

    finally:
        if cur is not None:
            cur.close()

        if conn is not None:
            conn.close()


async def _is_manager(user_id):
    return await asyncio.to_thread(_is_developer_sync, user_id)


def _save_requirement_sync(
    group_id,
    req_type,
    target_chat_id,
    target,
    title,
    join_url,
):
    conn = connect()
    cur = conn.cursor()

    try:
        if req_type == "start":
            cur.execute(
                """
                DELETE FROM mandatory_subscription_requirements
                WHERE group_id=? AND requirement_type='start'
                """,
                (group_id,),
            )

        cur.execute("""
            INSERT INTO mandatory_subscription_requirements
                (group_id, requirement_type, target_chat_id, target, title, join_url)
            VALUES (?, ?, ?, ?, ?, ?)
            ON CONFLICT (group_id, requirement_type, target)
            DO UPDATE SET target_chat_id=EXCLUDED.target_chat_id,
                          title=EXCLUDED.title,
                          join_url=EXCLUDED.join_url
        """, (
            group_id,
            req_type,
            target_chat_id,
            target,
            title,
            join_url,
        ))

        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


def _remove_requirement_sync(group_id, req_type, target=None):
    conn = connect()
    cur = conn.cursor()

    try:
        if req_type == "start":
            cur.execute(
                """
                DELETE FROM mandatory_subscription_requirements
                WHERE group_id=? AND requirement_type='start'
                """,
                (group_id,),
            )
        else:
            cur.execute(
                """
                DELETE FROM mandatory_subscription_requirements
                WHERE group_id=? AND requirement_type='chat' AND target=?
                """,
                (group_id, target),
            )

        count = cur.rowcount
        conn.commit()

        return count

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


def _set_enabled_sync(group_id, enabled, user_id):
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute("""
            INSERT INTO mandatory_subscription_settings
                (chat_id, enabled, updated_by, updated_at)
            VALUES (?, ?, ?, CURRENT_TIMESTAMP)
            ON CONFLICT(chat_id)
            DO UPDATE SET enabled=EXCLUDED.enabled,
                          updated_by=EXCLUDED.updated_by,
                          updated_at=CURRENT_TIMESTAMP
        """, (group_id, int(enabled), user_id))

        conn.commit()

    except Exception:
        conn.rollback()
        raise

    finally:
        cur.close()
        conn.close()


