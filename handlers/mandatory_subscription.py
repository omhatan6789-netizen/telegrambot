def _invalidate_group_config(group_id):
    """إبطال كاش إعدادات قروب بعد تعديل شروطه."""
    _group_config_cache.pop(group_id, None)


def _invalidate_membership_cache(target_chat_id, user_id=None):
    """إبطال كاش عضوية مستخدم أو جميع المستخدمين في قناة."""
    if user_id is not None:
        _membership_cache.pop((int(target_chat_id), int(user_id)), None)
        return

    target_chat_id = int(target_chat_id)

    for key in list(_membership_cache):
        if key[0] == target_chat_id:
            _membership_cache.pop(key, None)


def _get_group_config_sync(group_id):
    """
    تحميل إعدادات القروب وشروطه باستخدام اتصال واحد.
    """
    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute(
            """
            SELECT enabled
            FROM mandatory_subscription_settings
            WHERE chat_id=?
            """,
            (group_id,),
        )

        settings = cur.fetchone()

        cur.execute("""
            SELECT id, requirement_type, target_chat_id, target, title, join_url
            FROM mandatory_subscription_requirements
            WHERE group_id=?
            ORDER BY id
        """, (group_id,))

        rows = cur.fetchall()

        enabled = bool(settings and settings[0])

        return enabled, rows

    finally:
        cur.close()
        conn.close()


async def _get_group_config_cached(group_id):
    """
    إرجاع إعدادات القروب من الكاش.
    لا نرجع لقاعدة البيانات إلا عند انتهاء مدة الكاش أو غيابه.
    """
    now = time.monotonic()
    cached = _group_config_cache.get(group_id)

    if cached and now - cached[0] < GROUP_CONFIG_CACHE_TTL:
        return cached[1], cached[2]

    lock = _group_config_locks.get(group_id)

    if lock is None:
        lock = asyncio.Lock()
        _group_config_locks[group_id] = lock

    async with lock:
        # ربما حمّل طلب آخر الإعدادات أثناء انتظار القفل.
        now = time.monotonic()
        cached = _group_config_cache.get(group_id)

        if cached and now - cached[0] < GROUP_CONFIG_CACHE_TTL:
            return cached[1], cached[2]

        enabled, requirements = await asyncio.to_thread(
            _get_group_config_sync,
            group_id,
        )

        _group_config_cache[group_id] = (
            time.monotonic(),
            enabled,
            requirements,
        )

        return enabled, requirements


def _cache_enabled_state(group_id, enabled):
    """
    تحديث حالة التفعيل في الكاش إذا كانت إعدادات القروب محمّلة.
    """
    cached = _group_config_cache.get(group_id)

    if cached is None:
        return

    _group_config_cache[group_id] = (
        time.monotonic(),
        bool(enabled),
        cached[2],
    )


