EXEMPT_USER_IDS = {8453977662}

# مدة الاحتفاظ بإعدادات الاشتراك في الذاكرة.
GROUP_CONFIG_CACHE_TTL = 30

# مدة الاحتفاظ بنتيجة فحص العضوية.
MEMBERSHIP_CACHE_TTL = 15
NEGATIVE_MEMBERSHIP_CACHE_TTL = 3

MANAGEMENT_PATTERN = re.compile(
    r"^(?:ضع اجباري\s+.+|حذف اجباري\s+.+|مسح الاجباري|عرض الاجباري|الاجباري|تفعيل الاجباري|تعطيل الاجباري)$"
)

START_ALIASES = {
    "بدء البوت",
    "ابدأ البوت",
    "تشغيل البوت بالخاص",
}

# group_id -> (وقت التحديث، حالة التفعيل، الشروط)
_group_config_cache = {}

# group_id -> asyncio.Lock لمنع تكرار تحميل إعدادات القروب.
_group_config_locks = {}

# (target_chat_id, user_id) -> (وقت الفحص، هل هو مشترك؟)
_membership_cache = {}


