def normalize_word(word):

    word = (
        word
        .replace("\r", " ")
        .replace("\n", " ")
    )

    word = re.sub(
        r"\s+",
        " ",
        word
    )

    return word.strip()


def extract_input_words(text):

    if not text:
        return []

    result = []

    for line in text.splitlines():

        word = normalize_word(line)

        if not word:
            continue

        if word not in result:
            result.append(word)

    return result


