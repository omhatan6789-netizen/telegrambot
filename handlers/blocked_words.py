# ==================================================
# تطبيق نظام الإنذار
# ==================================================

async def handle_warning_punishment(
    update,
    context,
    chat_id,
    list_id,
    target,
    settings
):

    warning_duration = (
        settings["warning_duration"]
    )

    warning_action = (
        settings["warning_action"]
    )

    punishment_duration = (
        settings["warning_punishment_duration"]
    )

    if not warning_duration:
        return

    if not warning_action:
        return

    await asyncio.to_thread(
        add_blocked_warning,
        chat_id,
        list_id,
        target.id,
        warning_duration
    )

    count = await asyncio.to_thread(
        get_active_warning_count,
        chat_id,
        list_id,
        target.id
    )

    # ==================================================
    # أول وثاني إنذار
    # ==================================================

    if count < 3:

        await send_blocked_warning(
            update,
            target,
            count
        )

        return

    # ==================================================
    # الإنذار الثالث
    #
    # لا توجد رسالة اختيار.
    # العقوبة تنفذ مباشرة.
    # ==================================================

    await asyncio.to_thread(
        clear_blocked_warnings,
        chat_id,
        list_id,
        target.id
    )

    await apply_punishment(
        update,
        context,
        chat_id,
        target,
        warning_action,
        punishment_duration
    )


