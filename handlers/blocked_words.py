async def handle_blocked_session(
    update,
    context
):

    if not update.message:
        return False

    actor = update.effective_user

    if not actor:
        return False

    chat = update.effective_chat

    if not chat:
        return False

    key = (
        actor.id,
        chat.id
    )

    session = _blocked_sessions.get(
        key
    )

    if not session:
        return False

    # ==================================================
    # الصلاحية
    # ==================================================

    origin_chat_id = chat.id

    if not can_manage_blocked_words(
        actor.id,
        origin_chat_id
    ):

        _blocked_sessions.pop(
            key,
            None
        )

        await update.message.reply_text(
            BLOCKED_PERMISSION_MESSAGE
        )

        return True

    # ==================================================
    # إضافة كلمات
    # ==================================================

    if session["type"] == "add":

        words = extract_input_words(
            update.message.text or ""
        )

        list_id = session["list_id"]

        if not words:

            await update.message.reply_text(
                "• لم يتم العثور على كلمات لإضافتها ."
            )

            return True

        await asyncio.to_thread(
            add_words,
            origin_chat_id,
            list_id,
            words
        )

        _blocked_sessions.pop(
            key,
            None
        )

        try:
            await update.message.delete()
        except Exception:
            pass

        await update.message.reply_text(
            "تم حفظ الكلمات بنجاح ✅ .",
            reply_markup=InlineKeyboardMarkup(
                [
                    [
                        InlineKeyboardButton(
                            "↩️ رجوع لقائمة الكلمات",
                            callback_data=(
                                f"bw:back:"
                                f"{list_id}:"
                                f"{origin_chat_id}"
                            )
                        ),
                        InlineKeyboardButton(
                            "اغلاق القائمة",
                            callback_data=(
                                f"bw:close:"
                                f"{origin_chat_id}"
                            )
                        )
                    ]
                ]
            )
        )

        return True

    # ==================================================
    # حذف كلمات
    # ==================================================

    if session["type"] == "delete":

        words = extract_input_words(
            update.message.text or ""
        )

        list_id = session["list_id"]

        if not words:

            await update.message.reply_text(
                "• لم يتم العثور على كلمات لحذفها ."
            )

            return True

        await asyncio.to_thread(
            delete_words,
            origin_chat_id,
            list_id,
            words
        )

        _blocked_sessions.pop(
            key,
            None
        )

        try:
            await update.message.delete()
        except Exception:
            pass

        await update.message.reply_text(
            "تم حذف الكلمات بنجاح ✅ .",
            reply_markup=InlineKeyboardMarkup(
                [
                    [
                        InlineKeyboardButton(
                            "↩️ رجوع لقائمة الكلمات",
                            callback_data=(
                                f"bw:back:"
                                f"{list_id}:"
                                f"{origin_chat_id}"
                            )
                        ),
                        InlineKeyboardButton(
                            "اغلاق القائمة",
                            callback_data=(
                                f"bw:close:"
                                f"{origin_chat_id}"
                            )
                        )
                    ]
                ]
            )
        )

        return True

    # ==================================================
    # مدة العقوبة المباشرة
    # ==================================================

    if session["type"] == "direct_duration":

        token = (
            update.message.text or ""
        ).strip()

        duration = parse_duration_token(
            token
        )

        if duration is None:

            await update.message.reply_text(
                "• المدة غير صحيحة .\n"
                "• مثال: 5ي أو 30ث أو 50د أو 1س"
            )

            return True

        await asyncio.to_thread(
            set_direct_action,
            origin_chat_id,
            session["list_id"],
            session["action"],
            duration
        )

        _blocked_sessions.pop(
            key,
            None
        )

        await update.message.reply_text(
            "• تم حفظ إعداد العقوبة بنجاح ✅ ."
        )

        return True

    # ==================================================
    # إعداد الإنذار
    # ==================================================

    if session["type"] == "warning_setup":

        parts = (
            update.message.text or ""
        ).strip().split()

        if len(parts) not in (2, 3):

            await update.message.reply_text(
                "• الصيغة غير صحيحة .\n\n"
                "مثال:\n"
                "3د كتم 5ي"
            )

            return True

        warning_duration = parse_duration_token(
            parts[0]
        )

        if warning_duration is None:

            await update.message.reply_text(
                "• مدة الانذار غير صحيحة .\n\n"
                "مثال:\n"
                "3د كتم 5ي"
            )

            return True

        punishment_word = parts[1]

        punishment_map = {
            "كتم": "mute",
            "تقييد": "restrict",
            "حظر": "ban",
        }

        warning_action = punishment_map.get(
            punishment_word
        )

        if not warning_action:

            await update.message.reply_text(
                "• العقوبة غير صحيحة .\n\n"
                "استخدم: كتم أو تقييد أو حظر"
            )

            return True

        punishment_duration = None

        if warning_action in (
            "mute",
            "restrict"
        ):

            if len(parts) != 3:

                await update.message.reply_text(
                    "• يجب كتابة مدة العقوبة أيضًا .\n\n"
                    "مثال:\n"
                    "3د كتم 5ي"
                )

                return True

            punishment_duration = parse_duration_token(
                parts[2]
            )

            if punishment_duration is None:

                await update.message.reply_text(
                    "• مدة العقوبة غير صحيحة .\n\n"
                    "مثال:\n"
                    "3د كتم 5ي"
                )

                return True

        else:

            if len(parts) != 2:

                await update.message.reply_text(
                    "• الحظر دائم، اكتبها هكذا:\n\n"
                    "3د حظر"
                )

                return True

        await asyncio.to_thread(
            set_warning_action,
            origin_chat_id,
            session["list_id"],
            warning_duration,
            warning_action,
            punishment_duration
        )

        _blocked_sessions.pop(
            key,
            None
        )

        await update.message.reply_text(
            "• تم حفظ إعدادات الانذار بنجاح ✅ ."
        )

        return True

    return False


