def current_timestamp():

    return int(
        datetime.now(
            timezone.utc
        ).timestamp()
    )


def format_until(timestamp):

    if timestamp is None:
        return "لا توجد مدة"

    dt = datetime.fromtimestamp(
        timestamp,
        RIYADH_TZ
    )

    return dt.strftime(
        "%Y/%m/%d - %H:%M:%S"
    )


