        # إعداد العقوبة
        # --------------------------------------------------

        punishment_match = re.fullmatch(
            r"ضع عقوبة\s+"
            r"(الكلمات المحظورة|الكلمات المحظورة/ه|"
            r"الكلمات المحظورة2|الكلمات المحظورة/ه2)"
            r"\s+"
            r"(كتم|تقييد|حظر|انذار)",
            text
        )

