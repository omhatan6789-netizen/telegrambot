async def blocked_words_callback(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    query = update.callback_query

    if not query:
        return

    data = (
        query.data or ""
    )

    if not data.startswith(
        "bw:"
    ):
        return

    actor = query.from_user

    if not actor:
        return

    parts = data.split(":")

    if len(parts) < 2:
        return

    action = parts[1]

    # ==================================================
    # تحديد القائمة
    # ==================================================

    list_id = None
    origin_chat_id = None

    if action in (
        "here",
        "private",
        "add",
        "delete",
        "toggle",
        "back"
    ):

        if len(parts) != 4:
            await query.answer()
            return

        try:

            list_id = int(
                parts[2]
            )

            origin_chat_id = int(
                parts[3]
            )

        except Exception:

            await query.answer()
            return

    elif action == "close":

        if len(parts) != 3:

            await query.answer()
            return

        try:
            origin_chat_id = int(
                parts[2]
            )
        except Exception:
            await query.answer()
            return

    elif action == "lift":

        if len(parts) != 5:

            await query.answer()
            return

        punishment_action = parts[2]

        try:

            origin_chat_id = int(
                parts[3]
            )

            target_id = int(
                parts[4]
            )

        except Exception:

            await query.answer()
            return

        list_id = None

    else:

        await query.answer()
        return

    # ==================================================
    # صلاحية القوائم
    # ==================================================

    if not can_manage_blocked_words(
        actor.id,
        origin_chat_id
    ):

        await query.answer(
            BLOCKED_PERMISSION_MESSAGE,
            show_alert=True
        )

        return

    # ==================================================
    # هنا
    # ==================================================

    if action == "here":

        await query.answer()

        if not query.message:
            return

        text, keyboard = await asyncio.to_thread(
            build_list_message,
            origin_chat_id,
            list_id
        )

        await query.edit_message_text(
            text,
            parse_mode="HTML",
            reply_markup=keyboard
        )

        return

    # ==================================================
    # الخاص
    # ==================================================

    if action == "private":

        await query.answer()

        if not query.message:
            return

        text, keyboard = await asyncio.to_thread(
            build_list_message,
            origin_chat_id,
            list_id
        )

        try:

            await context.bot.send_message(
                chat_id=actor.id,
                text=text,
                parse_mode="HTML",
                reply_markup=keyboard
            )

            await query.edit_message_text(
                "تم الإرسال بالخاص ✅ ."
            )

        except Exception as e:

            print(
                f"⚠️ تعذر إرسال قائمة الكلمات بالخاص: {e}"
            )

            await query.edit_message_text(
                "تعذر إرسال القائمة بالخاص."
            )

        return

    # ==================================================
    # إضافة
    # ==================================================

    if action == "add":

        await query.answer()

        if not query.message:
            return

        # --------------------------------------------------
        # جلسة الإدخال تكون في نفس المحادثة التي ضغط منها
        # --------------------------------------------------

        session_chat_id = (
            query.message.chat.id
        )

        _blocked_sessions[
            (
                actor.id,
                session_chat_id
            )
        ] = {
            "type": "add",
            "list_id": list_id,
            "origin_chat_id": origin_chat_id,
        }

        await query.edit_message_text(
            "• حسنًا ارسل الكلمات التي تريد إضافتها .\n\n"
            "مثال:\n\n"
            "كلزق\n"
            "كلتبن\n"
            "ياكلب\n"
            "الخ…"
        )

        return

    # ==================================================
    # حذف
    # ==================================================

    if action == "delete":

        await query.answer()

        if not query.message:
            return

        session_chat_id = (
            query.message.chat.id
        )

        _blocked_sessions[
            (
                actor.id,
                session_chat_id
            )
        ] = {
            "type": "delete",
            "list_id": list_id,
            "origin_chat_id": origin_chat_id,
        }

        await query.edit_message_text(
            "• حسنًا ارسل الكلمات التي تريد حذفها .\n\n"
            "مثال:\n\n"
            "كلزق\n"
            "كلتبن\n"
            "ياكلب\n"
            "الخ…"
        )

        return

    # ==================================================
    # التفعيل / التعطيل
    # ==================================================

    if action == "toggle":

        settings = await asyncio.to_thread(
            get_settings,
            origin_chat_id,
            list_id
        )

        new_status = not settings[
            "enabled"
        ]

        await asyncio.to_thread(
            set_enabled,
            origin_chat_id,
            list_id,
            new_status
        )

        await query.answer(
            "تم تفعيل القائمة ✅"
            if new_status
            else
            "تم تعطيل القائمة ✅"
        )

        if not query.message:
            return

        text, keyboard = await asyncio.to_thread(
            build_list_message,
            origin_chat_id,
            list_id
        )

        await query.edit_message_text(
            text,
            parse_mode="HTML",
            reply_markup=keyboard
        )

        return

    # ==================================================
    # رجوع
    # ==================================================

    if action == "back":

        await query.answer()

        if not query.message:
            return

        text, keyboard = await asyncio.to_thread(
            build_list_message,
            origin_chat_id,
            list_id
        )

        await query.edit_message_text(
            text,
            parse_mode="HTML",
            reply_markup=keyboard
        )

        return

    # ==================================================
    # إغلاق
    # ==================================================

    if action == "close":

        await query.answer()

        if query.message:

            try:
                await query.message.delete()
            except Exception:
                pass

        return

    # ==================================================
    # رفع العقوبة
    # ==================================================

    if action == "lift":

        await query.answer()

        target = None

        try:

            chat_member = await context.bot.get_chat_member(
                origin_chat_id,
                target_id
            )

            target = chat_member.user

        except Exception:

            class StoredUser:
                pass

            target = StoredUser()
            target.id = target_id
            target.username = None
            target.first_name = str(
                target_id
            )

        # ==================================================
        # رفع الكتم
        # ==================================================

        if punishment_action == "mute":

            await asyncio.to_thread(
                delete_restriction_record,
                "bot_mutes",
                origin_chat_id,
                target_id
            )

        # ==================================================
        # رفع التقييد
        # ==================================================

        elif punishment_action == "restrict":

            try:

                permissions = ChatPermissions(
                    can_send_messages=True,
                    can_send_audios=True,
                    can_send_documents=True,
                    can_send_photos=True,
                    can_send_videos=True,
                    can_send_video_notes=True,
                    can_send_voice_notes=True,
                    can_send_polls=True,
                    can_send_other_messages=True,
                    can_add_web_page_previews=True,
                    can_invite_users=True,
                    can_manage_topics=True,
                )

                await context.bot.restrict_chat_member(
                    chat_id=origin_chat_id,
                    user_id=target_id,
                    permissions=permissions
                )

            except Exception as e:

                print(
                    f"⚠️ فشل رفع القيود: {e}"
                )

            await asyncio.to_thread(
                delete_restriction_record,
                "restrictions",
                origin_chat_id,
                target_id
            )

        # ==================================================
        # رفع الحظر
        # ==================================================

        elif punishment_action == "ban":

            try:

                await context.bot.unban_chat_member(
                    chat_id=origin_chat_id,
                    user_id=target_id,
                    only_if_banned=False
                )

            except Exception as e:

                print(
                    f"⚠️ فشل رفع الحظر: {e}"
                )

            await asyncio.to_thread(
                delete_restriction_record,
                "moderation_bans",
                origin_chat_id,
                target_id
            )

        if query.message:

            try:
                await query.edit_message_reply_markup(
                    reply_markup=None
                )
            except Exception:
                pass

        return


