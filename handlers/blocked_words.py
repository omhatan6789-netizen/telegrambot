def ensure_blocked_words_tables():

    conn = connect()
    cur = None

    try:

        cur = conn.cursor()

        # ==================================================
        # الكلمات
        #
        # list_id:
        # 1 = الكلمات المحظورة
        # 2 = الكلمات المحظورة2
        # ==================================================

        cur.execute("""
        CREATE TABLE IF NOT EXISTS blocked_words_v2
        (
            chat_id BIGINT NOT NULL,
            list_id INTEGER NOT NULL,
            word TEXT NOT NULL,

            PRIMARY KEY
            (
                chat_id,
                list_id,
                word
            )
        )
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS
        idx_blocked_words_v2_lookup
        ON blocked_words_v2
        (
            chat_id,
            list_id
        )
        """)

        # ==================================================
        # إعدادات القوائم
        # ==================================================

        cur.execute("""
        CREATE TABLE IF NOT EXISTS blocked_words_settings_v2
        (
            chat_id BIGINT NOT NULL,
            list_id INTEGER NOT NULL,

            enabled INTEGER DEFAULT 0,

            action TEXT DEFAULT 'mute',
            duration INTEGER,

            warning_duration INTEGER,
            warning_action TEXT,
            warning_punishment_duration INTEGER,

            PRIMARY KEY
            (
                chat_id,
                list_id
            )
        )
        """)

        # ==================================================
        # الأشخاص الذين فتحوا القائمة من قبل
        # ==================================================

        cur.execute("""
        CREATE TABLE IF NOT EXISTS blocked_words_opened_v2
        (
            chat_id BIGINT NOT NULL,
            list_id INTEGER NOT NULL,
            user_id BIGINT NOT NULL,

            PRIMARY KEY
            (
                chat_id,
                list_id,
                user_id
            )
        )
        """)

        # ==================================================
        # إنذارات الكلمات المؤقتة
        # ==================================================

        cur.execute("""
        CREATE TABLE IF NOT EXISTS blocked_words_warnings_v2
        (
            chat_id BIGINT NOT NULL,
            list_id INTEGER NOT NULL,
            user_id BIGINT NOT NULL,

            warning_id BIGINT
            GENERATED BY DEFAULT AS IDENTITY
            PRIMARY KEY,

            expires_at BIGINT NOT NULL,
            created_at BIGINT NOT NULL
        )
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS
        idx_blocked_words_warnings_lookup
        ON blocked_words_warnings_v2
        (
            chat_id,
            list_id,
            user_id
        )
        """)

        cur.execute("""
        CREATE INDEX IF NOT EXISTS
        idx_blocked_words_warnings_expiry
        ON blocked_words_warnings_v2
        (
            expires_at
        )
        """)

        # ==================================================
        # إنشاء إعدادات القائمتين
        # ==================================================

        cur.execute("""
        INSERT INTO blocked_words_settings_v2
        (
            chat_id,
            list_id
        )
        SELECT
            chat_id,
            1
        FROM blocked_words_settings
        ON CONFLICT
        (
            chat_id,
            list_id
        )
        DO NOTHING
        """)

        # ==================================================
        # نقل إعدادات النظام القديم للقائمة الأولى
        # ==================================================

        cur.execute("""
        UPDATE blocked_words_settings_v2 AS new
        SET
            enabled = old.enabled,
            action = old.action
        FROM blocked_words_settings AS old
        WHERE
            new.chat_id = old.chat_id
            AND new.list_id = 1
        """)

        # ==================================================
        # نقل الكلمات القديمة للقائمة الأولى
        # ==================================================

        cur.execute("""
        INSERT INTO blocked_words_v2
        (
            chat_id,
            list_id,
            word
        )
        SELECT
            chat_id,
            1,
            word
        FROM blocked_words
        ON CONFLICT
        (
            chat_id,
            list_id,
            word
        )
        DO NOTHING
        """)

        conn.commit()

    except Exception:

        conn.rollback()
        raise

    finally:

        if cur:
            cur.close()

        conn.close()


