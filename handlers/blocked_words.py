async def apply_punishment(
    update,
    context,
    chat_id,
    target,
    action,
    duration
):

    until_timestamp = None

    if duration is not None:

        until_timestamp = (
            current_timestamp()
            + int(duration)
        )

    until_time = None

    if until_timestamp is not None:

        until_time = (
            datetime.fromtimestamp(
                until_timestamp,
                timezone.utc
            ).isoformat()
        )

    # ==================================================
    # الكتم
    # ==================================================

    if action == "mute":

        await asyncio.to_thread(
            save_mute,
            chat_id,
            target,
            until_time,
            None,
            context.bot.id
        )

    # ==================================================
    # التقييد
    # ==================================================

    elif action == "restrict":

        try:

            permissions = ChatPermissions(
                can_send_messages=False
            )

            await context.bot.restrict_chat_member(
                chat_id=chat_id,
                user_id=target.id,
                permissions=permissions,
                until_date=(
                    until_timestamp
                    if until_timestamp
                    else None
                )
            )

        except Exception as e:

            print(
                f"⚠️ فشل تقييد مستخدم بسبب كلمة محظورة: {e}"
            )

            return False

        await asyncio.to_thread(
            save_restriction,
            chat_id,
            target,
            until_time,
            None,
            context.bot.id
        )

    # ==================================================
    # الحظر
    # ==================================================

    elif action == "ban":

        try:

            await context.bot.ban_chat_member(
                chat_id=chat_id,
                user_id=target.id,
                until_date=(
                    until_timestamp
                    if until_timestamp
                    else None
                )
            )

        except Exception as e:

            print(
                f"⚠️ فشل حظر مستخدم بسبب كلمة محظورة: {e}"
            )

            return False

        await asyncio.to_thread(
            save_ban,
            chat_id,
            target,
            until_time,
            None,
            context.bot.id
        )

    else:

        return False

    if update and update.message:

        await update.message.reply_text(
            punishment_message(
                action,
                target,
                until_timestamp
            ),
            parse_mode="HTML",
            reply_markup=punishment_keyboard(
                action,
                chat_id,
                target.id
            )
        )

    return True


