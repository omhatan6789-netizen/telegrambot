async def check_blocked_words(
    update,
    context
):

    if not update.message:
        return False

    if not update.effective_chat:
        return False

    # الكلمات المحظورة في القروبات فقط
    if update.effective_chat.type not in (
        "group",
        "supergroup"
    ):
        return False

    actor = update.effective_user

    if not actor:
        return False

    text = (
        update.message.text or ""
    )

    if not text:
        return False

    chat_id = (
        update.effective_chat.id
    )

    # ==================================================
    # القائمة الأولى والثانية
    # ==================================================

    for list_id in (
        LIST_1,
        LIST_2
    ):

        settings = await asyncio.to_thread(
            get_settings,
            chat_id,
            list_id
        )

        if not settings["enabled"]:
            continue

        words = await asyncio.to_thread(
            get_words,
            chat_id,
            list_id
        )

        if not words:
            continue

        matched = find_blocked_word(
            text,
            words
        )

        if not matched:
            continue

        # ==================================================
        # حفظ المستخدم
        # ==================================================

        try:

            from handlers.moderation import (
                save_target_user
            )

            await asyncio.to_thread(
                save_target_user,
                actor
            )

        except Exception:
            pass

        # ==================================================
        # عقوبة مباشرة
        # ==================================================

        if settings["action"] in (
            "mute",
            "restrict",
            "ban"
        ):

            duration = settings[
                "duration"
            ]

            await apply_punishment(
                update,
                context,
                chat_id,
                actor,
                settings["action"],
                duration
            )

            return True

        # ==================================================
        # عقوبة الإنذار
        # ==================================================

        if settings["action"] == "warning":

            await handle_warning_punishment(
                update,
                context,
                chat_id,
                list_id,
                actor,
                settings
            )

            return True

    return False


