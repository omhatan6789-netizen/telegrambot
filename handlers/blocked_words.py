def word_matches(
    text,
    word
):

    if not text or not word:
        return False

    word = normalize_word(word)

    if not word:
        return False

    escaped = re.escape(word)

    # --------------------------------------------------
    # \w في Python Unicode-aware
    #
    # لذلك:
    #
    # ياكلب😂       = يطابق
    # ياكلب ههههه   = يطابق
    # ياكلب…….      = يطابق
    #
    # ياكلبك        = لا يطابق
    # --------------------------------------------------

    pattern = (
        rf"(?<!\w)"
        rf"{escaped}"
        rf"(?!\w)"
    )

    return bool(
        re.search(
            pattern,
            text,
            flags=re.UNICODE
        )
    )


def find_blocked_word(
    text,
    words
):

    for word in words:

        if word_matches(
            text,
            word
        ):
            return word

    return None


