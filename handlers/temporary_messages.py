def _scope(update, text):
    text = text.strip()

    if text.endswith(" عام"):
        return "global", 0, text[:-4].strip()

    return "chat", update.effective_chat.id, text


def _get_rows(scope, chat_id):
    conn = connect()
    cur = conn.cursor()

    try:
        if scope == "global":
            cur.execute("""
                SELECT id, payload, buttons, interval_seconds, next_run_at
                FROM temporary_messages
                WHERE scope=?
                ORDER BY id
            """, ("global",))
        else:
            cur.execute("""
                SELECT id, payload, buttons, interval_seconds, next_run_at
                FROM temporary_messages
                WHERE scope=? AND chat_id=?
                ORDER BY id
            """, ("chat", chat_id))

        return cur.fetchall()

    finally:
        cur.close()
        conn.close()


def _get_row(scope, chat_id, number):
    rows = _get_rows(scope, chat_id)

    if 1 <= number <= len(rows):
        return rows[number - 1]

    return None


def _get_row_by_id(scope, chat_id, row_id):
    conn = connect()
    cur = conn.cursor()

    try:
        if scope == "global":
            cur.execute("""
                SELECT id, payload, buttons, interval_seconds, next_run_at
                FROM temporary_messages
                WHERE id=? AND scope='global'
            """, (row_id,))
        else:
            cur.execute("""
                SELECT id, payload, buttons, interval_seconds, next_run_at
                FROM temporary_messages
                WHERE id=? AND scope='chat' AND chat_id=?
            """, (row_id, chat_id))

        return cur.fetchone()

    finally:
        cur.close()
        conn.close()


