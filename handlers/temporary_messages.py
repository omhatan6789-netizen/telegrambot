# إرسال الرسائل في وقتها المحدد
# ==========================================

async def temporary_message_scheduler(application):
    while True:
        try:
            now = time.time()

            conn = connect()
            cur = conn.cursor()

            try:
                cur.execute(
                    """
                    SELECT id, scope, chat_id, payload, buttons,
                           interval_seconds
                    FROM temporary_messages
                    WHERE interval_seconds IS NOT NULL
                      AND next_run_at IS NOT NULL
                      AND next_run_at<=?
                    """,
                    (now,),
                )

                due = cur.fetchall()

                for row in due:
                    cur.execute(
                        """
                        UPDATE temporary_messages
                        SET next_run_at=?
                        WHERE id=? AND next_run_at<=?
                        """,
                        (
                            now + int(row[5]),
                            row[0],
                            now,
                        ),
                    )

                conn.commit()

            finally:
                cur.close()
                conn.close()

            for row in due:
                if row[1] == "global":
                    conn = connect()
                    cur = conn.cursor()

                    try:
                        cur.execute(
                            """
                            SELECT chat_id
                            FROM temporary_message_chats
                            WHERE active=1
                            """
                        )

                        chats = [
                            item[0]
                            for item in cur.fetchall()
                        ]

                    finally:
                        cur.close()
                        conn.close()

                else:
                    chats = [row[2]]

                payload = json.loads(row[3])
                buttons = json.loads(row[4] or "[]")

                for target_chat_id in chats:
                    try:
                        await _send_payload(
                            application.bot,
                            target_chat_id,
                            payload,
                            buttons,
                        )

                    except Forbidden:
                        if row[1] == "global":
                            conn = connect()
                            cur = conn.cursor()

                            try:
                                cur.execute(
                                    """
                                    UPDATE temporary_message_chats
                                    SET active=0
                                    WHERE chat_id=?
                                    """,
                                    (target_chat_id,),
                                )
                                conn.commit()

                            finally:
                                cur.close()
                                conn.close()

                    except (TelegramError, ValueError) as exc:
                        print(
                            "⚠️ تعذر إرسال الرسالة المؤقتة "
                            f"{row[0]} إلى {target_chat_id}: {exc}"
                        )

        except asyncio.CancelledError:
            raise

        except Exception as exc:
            print(
                f"⚠️ خطأ في مجدول الرسائل المؤقتة: {exc}"
            )

        await asyncio.sleep(5)


