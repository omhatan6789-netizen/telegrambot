# تسجيل القروبات لاستقبال الرسائل العامة
# ==========================================

async def track_temporary_message_chat(update, context):
    chat = update.effective_chat

    if not chat or chat.type not in ("group", "supergroup"):
        return

    conn = connect()
    cur = conn.cursor()

    try:
        cur.execute(
            """
            INSERT INTO temporary_message_chats
            (chat_id, title, active, updated_at)
            VALUES (?, ?, 1, ?)
            ON CONFLICT(chat_id)
            DO UPDATE SET
                title=excluded.title,
                active=1,
                updated_at=excluded.updated_at
            """,
            (
                chat.id,
                chat.title or "",
                time.time(),
            ),
        )

        conn.commit()

    except Exception:
        conn.rollback()

    finally:
        cur.close()
        conn.close()
