def _markup(buttons):
    if not buttons:
        return None

    return InlineKeyboardMarkup([
        [
            InlineKeyboardButton(
                button["text"],
                url=button["url"],
            )
            for button in row
        ]
        for row in buttons
    ])


async def _send_payload(bot, chat_id, payload, buttons):
    kind = payload.get("type")
    markup = _markup(buttons)

    caption = payload.get("caption") or None

    caption_entities = [
        MessageEntity.de_json(entity, bot)
        for entity in payload.get("caption_entities", [])
    ]

    if kind == "text":
        entities = [
            MessageEntity.de_json(entity, bot)
            for entity in payload.get("entities", [])
        ]

        return await bot.send_message(
            chat_id=chat_id,
            text=payload.get("text") or " ",
            entities=entities or None,
            reply_markup=markup,
        )

    file_id = payload["file_id"]

    if kind == "photo":
        return await bot.send_photo(
            chat_id, file_id,
            caption=caption,
            caption_entities=caption_entities or None,
            reply_markup=markup,
        )

    if kind == "video":
        return await bot.send_video(
            chat_id, file_id,
            caption=caption,
            caption_entities=caption_entities or None,
            reply_markup=markup,
        )

    if kind == "animation":
        return await bot.send_animation(
            chat_id, file_id,
            caption=caption,
            caption_entities=caption_entities or None,
            reply_markup=markup,
        )

    if kind == "document":
        return await bot.send_document(
            chat_id, file_id,
            caption=caption,
            caption_entities=caption_entities or None,
            reply_markup=markup,
        )

    if kind == "audio":
        return await bot.send_audio(
            chat_id, file_id,
            caption=caption,
            caption_entities=caption_entities or None,
            title=payload.get("title"),
            performer=payload.get("performer"),
            reply_markup=markup,
        )

    if kind == "voice":
        return await bot.send_voice(
            chat_id, file_id,
            caption=caption,
            caption_entities=caption_entities or None,
            reply_markup=markup,
        )

    if kind == "video_note":
        sent = await bot.send_video_note(chat_id, file_id)

        if markup:
            await bot.send_message(
                chat_id, "‎",
                reply_markup=markup,
            )

        return sent

    if kind == "sticker":
        sent = await bot.send_sticker(chat_id, file_id)

        if markup:
            await bot.send_message(
                chat_id, "‎",
                reply_markup=markup,
            )

        return sent

    raise ValueError("نوع الرسالة غير مدعوم")


