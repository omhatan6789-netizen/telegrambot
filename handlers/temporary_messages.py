async def temporary_message_callback(update, context):
    query = update.callback_query
    await query.answer()

    parts = query.data.split(":")

    if len(parts) != 5:
        return

    _, action, scope, chat_text, id_text = parts

    chat_id = int(chat_text)
    row_id = int(id_text)
    user = query.from_user

    if scope == "global":
        if user.id != OWNER_ID:
            await query.answer(
                "هذا للمطور فقط.",
                show_alert=True,
            )
            return

    elif user.id != OWNER_ID and not is_admin(user.id):
        await query.answer(
            "هذا للمشرفين وفوق فقط.",
            show_alert=True,
        )
        return

    row = _get_row_by_id(scope, chat_id, row_id)

    if not row:
        await query.answer(
            "الرسالة غير موجودة.",
            show_alert=True,
        )
        return


    if action == "edit":
        context.user_data["temporary_message_pending"] = {
            "scope": scope,
            "chat_id": chat_id,
            "creator_id": user.id,
            "stage": "edit_content",
            "row_id": row_id,
        }

        await query.message.reply_text(
            "ارسل تنسيق الرسالة من جديد بدون الأزرار.\n"
            "لإلغاء التعديل، أرسل: إلغاء"
        )
        return

    if action == "buttons":
        context.user_data["temporary_message_pending"] = {
            "scope": scope,
            "chat_id": chat_id,
            "creator_id": user.id,
            "stage": "edit_buttons",
            "row_id": row_id,
        }

        await query.message.reply_text(
            "أرسل الأزرار الجديدة بهذا الشكل:\n"
            "[قناتي 🌷 - @channel]\n"
            "[حسابي 🌹 - @username]\n"
            "كل سطر صف مستقل.\n"
            "لإزالة جميع الأزرار أرسل: حذف الكل"
        )
        return
      
    if action == "list":
        await _show_list(query.message, scope, chat_id)
        return

    payload = json.loads(row[1])
    buttons = json.loads(row[2] or "[]")

    rows = _get_rows(scope, chat_id)

    number = next(
        (
            index
            for index, item in enumerate(rows, 1)
            if item[0] == row_id
        ),
        0,
    )

    content = (
        payload.get("text")
        or payload.get("caption")
        or f"[{payload.get('type', 'وسائط')}]"
    )

    button_info = []
    index = 0

    for button_row in buttons:
        for button in button_row:
            index += 1
            button_info.append(
                f"{index} ~ اسم الزر: ( {button['text']} ) "
                f"معلومات الزر: ( {button['url']} )"
            )

    display = (
        f"الرسالة {number}:\n{content}\n\n"
        "الأزرار المضافة بالرسالة:\n"
        + (
            "\n".join(button_info)
            if button_info
            else "لا توجد أزرار."
        )
    )

    markup = InlineKeyboardMarkup([
        [
            InlineKeyboardButton(
                "تعديل الرسالة",
                callback_data=(
                    f"tmp:edit:{scope}:{chat_id}:{row_id}"
                ),
            ),
        ],
        [
            InlineKeyboardButton(
                "تعديل الأزرار",
                callback_data=(
                    f"tmp:buttons:{scope}:{chat_id}:{row_id}"
                ),
            ),
        ],
        [
            InlineKeyboardButton(
                "رجوع للقائمة",
                callback_data=(
                    f"tmp:list:{scope}:{chat_id}:{row_id}"
                ),
            ),
        ],
    ])

    await query.message.reply_text(
        display[:4000],
        reply_markup=markup,
    )

    if payload.get("type") != "text":
        await _send_payload(
            context.bot,
            query.message.chat_id,
            payload,
            buttons,
        )


