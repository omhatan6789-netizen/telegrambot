def _parse_buttons(text):
    buttons = []
    kept_lines = []

    pattern = re.compile(
        r"\[([^\[\]]+?)\s+-\s+([^\[\]]+?)\]"
    )

    for line in (text or "").splitlines():
        matches = list(pattern.finditer(line))

        if (
            matches
            and "".join(m.group(0) for m in matches).replace(" ", "")
            == line.replace(" ", "")
        ):
            row = []

            for match in matches:
                label = match.group(1).strip()
                target = match.group(2).strip()

                if target.startswith("@"):
                    target = "https://t.me/" + target[1:]

                parsed = urlparse(target)

                if (
                    label
                    and parsed.scheme in ("https", "http")
                    and parsed.netloc
                ):
                    row.append({
                        "text": label,
                        "url": target,
                    })

            if row:
                buttons.append(row)
        else:
            kept_lines.append(line)

    return "\n".join(kept_lines).strip(), buttons


def _payload_from_message(message):
    if message.text is not None:
        content, buttons = _parse_buttons(message.text)

        return {
            "type": "text",
            "text": content,
            "entities": [
                entity.to_dict()
                for entity in (message.entities or [])
            ],
        }, buttons

    caption, buttons = _parse_buttons(message.caption or "")

    payload = {
        "caption": caption,
        "caption_entities": [
            entity.to_dict()
            for entity in (message.caption_entities or [])
        ],
    }

    media_types = (
        ("photo", "photo"),
        ("video", "video"),
        ("animation", "animation"),
        ("document", "document"),
        ("audio", "audio"),
        ("voice", "voice"),
        ("video_note", "video_note"),
        ("sticker", "sticker"),
    )

    for attribute, kind in media_types:
        item = getattr(message, attribute, None)

        if not item:
            continue

        if kind == "photo":
            item = item[-1]

        payload.update({
            "type": kind,
            "file_id": item.file_id,
        })

        if kind == "audio":
            payload["title"] = item.title
            payload["performer"] = item.performer

        return payload, buttons

    return None, []


