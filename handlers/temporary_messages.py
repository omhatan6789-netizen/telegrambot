async def _show_list(message, scope, chat_id):
    rows = _get_rows(scope, chat_id)

    if scope == "global":
        title = "قائمة الرسائل المؤقتة العامة:"
    else:
        title = "قائمة الرسائل المؤقتة بالقروب:"

    if not rows:
        await message.reply_text(
            title + "\n• ما فيه رسائل مؤقتة."
        )
        return

    lines = [title]
    buttons = []

    for number, row in enumerate(rows, 1):
        payload = json.loads(row[1])

        raw = (
            payload.get("text")
            or payload.get("caption")
            or "[رسالة وسائط]"
        )

        words = raw.split()
        preview = " ".join(words[:4])

        if len(words) > 4:
            preview += "..."

        timing = (
            f" — كل {_format_duration(row[3])}"
            if row[3]
            else " — لم يحدد الوقت"
        )

        lines.append(
            f"{number} ~ {preview or 'رسالة وسائط'}{timing}"
        )

        buttons.append(
            InlineKeyboardButton(
                f"عرض الرسالة {number}",
                callback_data=(
                    f"tmp:view:{scope}:{chat_id}:{row[0]}"
                ),
            )
        )

    keyboard = [
        buttons[index:index + 2]
        for index in range(0, len(buttons), 2)
    ]

    await message.reply_text(
        "\n".join(lines),
        reply_markup=InlineKeyboardMarkup(keyboard),
    )


