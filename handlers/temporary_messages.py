async def temporary_message_pending_handler(update, context):
    message = update.effective_message
    user = update.effective_user
    chat = update.effective_chat

    if not message or not user or not chat:
        return

    if chat.type not in ("group", "supergroup"):
        return

    # لا تعالج أوامر إدارة الرسائل على أنها محتوى الرسالة المؤقتة
    if message.text and re.match(
        r"^(?:اضف رسالة مؤقتة|اضف رساله مؤقته"
        r"|الرسائل المؤقتة|الرسائل المؤقته"
        r"|مسح الرسالة المؤقتة \d+"
        r"|مسح الرساله المؤقته \d+"
        r"|مسح الرسائل المؤقتة|مسح الرسائل المؤقته"
        r"|ضع الرسالة \d+)(?: عام)?$",
        message.text.strip(),
    ):
        return

    pending = context.user_data.get("temporary_message_pending")
    if not pending:
        return

    if pending.get("creator_id") != user.id:
        return

    text = (message.text or "").strip()

    # إلغاء العملية الحالية
    if text == "إلغاء":
        context.user_data.pop("temporary_message_pending", None)
        await message.reply_text("تم إلغاء العملية.")
        return

    scope = pending.get("scope", "chat")
    target_chat_id = pending.get("chat_id", chat.id)
    row_id = pending.get("row_id")
    stage = pending.get("stage")

    # تعديل أزرار رسالة موجودة
    if stage == "edit_buttons":
        if text == "حذف الكل":
            buttons = []
        else:
            buttons = _parse_buttons(message.text or "")

            if not buttons:
                await message.reply_text(
                    "ما لقيت أزرارًا بالتنسيق الصحيح.\n"
                    "مثال:\n"
                    "[قناتي 🌷 - @channel]\n"
                    "[حسابي 🌹 - @username]\n\n"
                    "لإزالة جميع الأزرار أرسل: حذف الكل\n"
                    "ولإلغاء العملية أرسل: إلغاء"
                )
                return

        try:
            with connect() as conn:
                cur = conn.cursor()
                cur.execute(
                    """
                    UPDATE temporary_messages
                    SET buttons = ?
                    WHERE id = ? AND scope = ? AND chat_id = ?
                    """,
                    (
                        json.dumps(buttons, ensure_ascii=False),
                        row_id,
                        scope,
                        target_chat_id,
                    ),
                )
                conn.commit()

        except Exception:
            await message.reply_text(
                "تعذر حفظ الأزرار. تأكد من إعداد قاعدة البيانات."
            )
            return

        context.user_data.pop("temporary_message_pending", None)
        await message.reply_text("تم تحديث أزرار الرسالة المؤقتة بنجاح.")
        return

    # استقبال محتوى الرسالة الجديدة أو محتوى بديل للتعديل
    payload = _payload_from_message(message)

    if not payload:
        await message.reply_text(
            "أرسل نصًا أو صورة أو فيديو أو ملفًا أو صوتًا أو ملصقًا."
        )
        return

    # استخراج الأزرار المكتوبة داخل النص أو الوصف
    content_text = payload.get("text") or payload.get("caption") or ""
    buttons = _parse_buttons(content_text)

    if buttons:
        cleaned_text = re.sub(
            r"\[[^\]\n]+?\s+-\s+https?://[^\]\n]+\]"
            r"|\[[^\]\n]+?\s+-\s+@[A-Za-z0-9_]+\]",
            "",
            content_text,
        ).strip()

        if "text" in payload:
            payload["text"] = cleaned_text
        elif "caption" in payload:
            payload["caption"] = cleaned_text

    # تعديل محتوى رسالة موجودة
    if stage == "edit_content":
        try:
            with connect() as conn:
                cur = conn.cursor()
                cur.execute(
                    """
                    UPDATE temporary_messages
                    SET payload = ?, buttons = ?
                    WHERE id = ? AND scope = ? AND chat_id = ?
                    """,
                    (
                        json.dumps(payload, ensure_ascii=False),
                        json.dumps(buttons, ensure_ascii=False),
                        row_id,
                        scope,
                        target_chat_id,
                    ),
                )
                conn.commit()

        except Exception:
            await message.reply_text(
                "تعذر حفظ التعديل. تأكد من إعداد قاعدة البيانات."
            )
            return

        context.user_data.pop("temporary_message_pending", None)
        await message.reply_text("تم تعديل الرسالة المؤقتة بنجاح.")
        return

    # إضافة رسالة مؤقتة جديدة
    try:
        with connect() as conn:
            cur = conn.cursor()
            cur.execute(
                """
                SELECT COUNT(*)
                FROM temporary_messages
                WHERE scope = ? AND chat_id = ?
                """,
                (scope, target_chat_id),
            )
            count = cur.fetchone()[0]

            if count >= 8:
                context.user_data.pop("temporary_message_pending", None)
                await message.reply_text(
                    "وصلت للحد الأقصى، وهو 8 رسائل مؤقتة لهذا النطاق."
                )
                return

            cur.execute(
                """
                INSERT INTO temporary_messages
                (
                    scope, chat_id, creator_id, payload,
                    buttons, interval_seconds, next_run_at, created_at
                )
                VALUES (?, ?, ?, ?, ?, NULL, NULL, ?)
                """,
                (
                    scope,
                    target_chat_id,
                    user.id,
                    json.dumps(payload, ensure_ascii=False),
                    json.dumps(buttons, ensure_ascii=False),
                    time.time(),
                ),
            )
            conn.commit()

    except Exception:
        await message.reply_text(
            "تعذر حفظ الرسالة المؤقتة. تأكد من إعداد قاعدة البيانات."
        )
        return

    context.user_data.pop("temporary_message_pending", None)
    await message.reply_text(
        "تمت إضافة الرسالة المؤقتة بنجاح.\n"
        "لتحديد وقت تكرارها استخدم:\n"
        "ضع الرسالة رقم"
        + (" عام" if scope == "global" else "")
    )


