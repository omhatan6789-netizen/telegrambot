# تنظيف الرسائل القديمة من الكاش
# ==================================================

def cleanup_user_messages(
    chat_id,
    user_id,
    seconds
):

    now = datetime.now(
        timezone.utc
    )

    messages = _repetition_messages[
        chat_id
    ][
        user_id
    ]

    while messages:

        _, created_at = messages[0]

        age = (
            now - created_at
        ).total_seconds()

        if age <= seconds:
            break

        messages.popleft()


# ==================================================
# إضافة رسالة
# ==================================================

def add_repetition_message(
    chat_id,
    user_id,
    message_id,
    seconds
):

    cleanup_user_messages(
        chat_id,
        user_id,
        seconds
    )

    messages = _repetition_messages[
        chat_id
    ][
        user_id
    ]

    now = datetime.now(
        timezone.utc
    )

    messages.append(
        (
            message_id,
            now
        )
    )

    return list(messages)


# ==================================================
# جلب آخر N رسائل
# ==================================================

def get_last_repetition_messages(
    chat_id,
    user_id,
    limit
):

    messages = _repetition_messages[
        chat_id
    ][
        user_id
    ]

    if not messages:
        return []

    return [
        message_id
        for message_id, _ in list(
            messages
        )[-limit:]
    ]


