def create_repetition_tables():

    conn = connect()
    cur = None

    try:

        cur = conn.cursor()

        # --------------------------------------------------
        # إعدادات التكرار القديمة التي ما زالت مستخدمة
        # --------------------------------------------------

        columns = {
            "repetition_punishment_duration": (
                "INTEGER DEFAULT 300"
            ),
            "repetition_rank": (
                "TEXT DEFAULT 'عضو'"
            ),
        }

        for column, definition in columns.items():

            cur.execute(
                f"""
                ALTER TABLE protection_settings
                ADD COLUMN IF NOT EXISTS {column} {definition}
                """
            )

        # --------------------------------------------------
        # جدول الإنذارات الجديد موجود في database.py
        #
        # warnings:
        # chat_id
        # user_id
        # warning_id
        # source
        # created_at
        #
        # لا ننشئ جدول repetition_warnings الجديد
        # لأن الإنذارات اليدوية والتكرار أصبحت في نفس الجدول.
        # --------------------------------------------------

        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS warnings
            (
                chat_id BIGINT NOT NULL,
                user_id BIGINT NOT NULL,
                warning_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source TEXT NOT NULL DEFAULT 'manual',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """
        )

        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS
            idx_warnings_user
            ON warnings
            (
                chat_id,
                user_id
            )
            """
        )

        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS
            idx_warnings_created
            ON warnings
            (
                chat_id,
                user_id,
                created_at
            )
            """
        )

        conn.commit()

    except Exception as e:

        try:
            conn.rollback()
        except Exception:
            pass

        print(
            "❌ خطأ في إنشاء جداول التكرار:",
            e
        )

        raise

    finally:

        if cur is not None:

            try:
                cur.close()
            except Exception:
                pass

        conn.close()


