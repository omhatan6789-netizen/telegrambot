async def _get_warning_target(
    update,
    context
):

    if not update.message:
        return None

    # --------------------------------------------------
    # بالرد
    # --------------------------------------------------

    if update.message.reply_to_message:

        target = (
            update.message.reply_to_message.from_user
        )

        if target:
            return target

    # --------------------------------------------------
    # بالآيدي أو username
    # --------------------------------------------------

    text = (
        update.message.text or ""
    ).strip()

    parts = text.split()

    for value in parts[2:]:

        value = value.strip()

        if value.isdigit():

            try:

                return await context.bot.get_chat(
                    int(value)
                )

            except Exception:

                continue

        if value.startswith("@"):

            try:

                return await context.bot.get_chat(
                    value
                )

            except Exception:

                continue

    return None


