# ==================================================

def get_repetition_settings(chat_id):

    cached = _repetition_settings_cache.get(
        chat_id
    )

    if cached is not None:
        return cached.copy()

    ensure_repetition_settings(
        chat_id
    )

    conn = connect()
    cur = None

    try:

        cur = conn.cursor()

        cur.execute(
            """
            SELECT
                repetition_enabled,
                repetition_limit,
                repetition_seconds,
                repetition_action,
                repetition_punishment_duration,
                repetition_rank
            FROM protection_settings
            WHERE chat_id=?
            """,
            (
                chat_id,
            )
        )

        row = cur.fetchone()

    finally:

        if cur is not None:

            try:
                cur.close()
            except Exception:
                pass

        conn.close()

    if not row:

        settings = {
            "enabled": False,
            "limit": DEFAULT_LIMIT,
            "seconds": DEFAULT_SECONDS,
            "action": "mute",
            "punishment_duration": DEFAULT_PUNISHMENT_DURATION,
            "rank": "عضو",
        }

    else:

        settings = {
            "enabled": bool(row[0]),

            "limit": max(
                1,
                int(
                    row[1]
                    or DEFAULT_LIMIT
                )
            ),

            "seconds": max(
                1,
                int(
                    row[2]
                    or DEFAULT_SECONDS
                )
            ),

            "action": (
                row[3]
                if row[3] in (
                    "mute",
                    "restrict",
                    "ban",
                )
                else "mute"
            ),

            "punishment_duration": max(
                1,
                int(
                    row[4]
                    or DEFAULT_PUNISHMENT_DURATION
                )
            ),

            "rank": (
                row[5]
                if row[5] in RANK_LEVELS
                else "عضو"
            ),
        }

    _repetition_settings_cache[
        chat_id
    ] = settings.copy()

    return settings


