def _user_mention(user):

    name = (
        getattr(
            user,
            "first_name",
            None
        )
        or getattr(
            user,
            "full_name",
            None
        )
        or "المستخدم"
    )

    return (
        f'<a href="tg://user?id={user.id}">'
        f'{name}'
        f'</a>'
    )


# ==================================================
# تنفيذ عقوبة التكرار
#
# العقوبة يتم اختيارها يدويًا من زر:
# كتم / تقييد
# ==================================================

async def punish_user(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
    user,
    action,
    punishment_duration
):

    if not update.effective_chat:
        return False

    chat_id = update.effective_chat.id

    now = int(
        datetime.now(
            timezone.utc
        ).timestamp()
    )

    until_timestamp = None

    if (
        action in (
            "mute",
            "restrict",
        )
        and punishment_duration
    ):

        until_timestamp = (
            now + int(
                punishment_duration
            )
        )

    until_time = None

    if until_timestamp is not None:

        until_time = datetime.fromtimestamp(
            until_timestamp,
            timezone.utc
        ).isoformat()

    # ==================================================
    # الكتم
    # ==================================================

    if action == "mute":

        try:

            await asyncio.to_thread(
                save_mute,
                chat_id,
                user,
                until_time,
                "التكرار",
                context.bot.id
            )

        except Exception as e:

            print(
                f"❌ خطأ في كتم التكرار: {e}"
            )

            return False

        return True

    # ==================================================
    # التقييد
    # ==================================================

    if action == "restrict":

        try:

            permissions = ChatPermissions(
                can_send_messages=False
            )

            await context.bot.restrict_chat_member(
                chat_id=chat_id,
                user_id=user.id,
                permissions=permissions,
                until_date=until_timestamp
            )

            await asyncio.to_thread(
                save_restriction,
                chat_id,
                user,
                until_time,
                "التكرار",
                context.bot.id
            )

        except Exception as e:

            print(
                f"❌ خطأ في تقييد التكرار: {e}"
            )

            return False

        return True

    return False


