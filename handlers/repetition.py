async def receive_repetition_duration(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    if not update.message:
        return

    user = update.effective_user
    chat = update.effective_chat

    if not user or not chat:
        return

    session_key = (
        chat.id,
        user.id
    )

    session = repetition_sessions.get(
        session_key
    )

    if not session:
        return

    if session.get(
        "type"
    ) != "repetition_duration":
        return

    text = (
        update.message.text or ""
    ).strip()

    command_like_patterns = (
        r"^تفعيل التكرار$",
        r"^تعطيل التكرار$",
        r"^ضع تكرار(?:\s+\d+)?$",
        r"^ضع رتبة التكرار\s+",
        r"^تغيير رتبة التكرار\s+",
        r"^مسح انذاراته",
    )

    for pattern in command_like_patterns:

        if re.match(
            pattern,
            text,
            flags=re.IGNORECASE
        ):

            return

    duration = parse_duration_token(
        text
    )

    if duration is None:

        await update.message.reply_text(
            "❌ المدة غير صحيحة.\n"
            "أمثلة: 3ث - 5د - 1س - 2ي"
        )

        return

    update_repetition_setting(
        chat.id,
        "repetition_limit",
        session["limit"]
    )

    update_repetition_setting(
        chat.id,
        "repetition_seconds",
        duration
    )

    repetition_sessions.pop(
        session_key,
        None
    )

    await update.message.reply_text(
        "✅ تم حفظ إعداد التكرار.\n\n"
        f"عدد الرسائل ↤︎ {session['limit']}\n"
        f"المدة ↤︎ {format_duration(duration)}"
    )


