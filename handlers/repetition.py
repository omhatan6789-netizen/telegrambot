DURATION_PATTERN = re.compile(
    r"^\s*(\d+(?:\.\d+)?)\s*"
    r"(ث|ثانية|ثواني|د|دقيقة|دقائق|س|ساعة|ساعات|ي|يوم|أيام)"
    r"\s*$"
)


def parse_duration_token(token):

    if not token:
        return None

    match = DURATION_PATTERN.match(
        str(token)
    )

    if not match:
        return None

    try:

        number = float(
            match.group(1)
        )

    except Exception:

        return None

    if number < 1:
        return None

    unit = match.group(2)

    if unit in (
        "ث",
        "ثانية",
        "ثواني",
    ):

        multiplier = 1

    elif unit in (
        "د",
        "دقيقة",
        "دقائق",
    ):

        multiplier = 60

    elif unit in (
        "س",
        "ساعة",
        "ساعات",
    ):

        multiplier = 3600

    else:

        multiplier = 86400

    seconds = int(
        number * multiplier
    )

    if seconds < 1:
        return None

    return seconds


# ==================================================
# تنسيق المدة
# ==================================================

def format_duration(seconds):

    seconds = int(seconds)

    if seconds % 86400 == 0:

        value = seconds // 86400

        return f"{value} يوم"

    if seconds % 3600 == 0:

        value = seconds // 3600

        return f"{value} ساعة"

    if seconds % 60 == 0:

        value = seconds // 60

        return f"{value} دقيقة"

    return f"{seconds} ثانية"


