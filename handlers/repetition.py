# Callback اختيار عقوبة الإنذار الثالث
#
# repetition_punish:restrict:user_id
# repetition_punish:mute:user_id
# ==================================================

async def repetition_action_callback(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    query = update.callback_query

    if not query:
        return

    actor = query.from_user

    if not actor:
        return

    message = query.message

    if not message:
        return

    chat = message.chat

    if not chat:
        return

    data = query.data or ""

    # ==================================================
    # السماح فقط للـ callback الجديد
    # ==================================================

    if not data.startswith(
        "repetition_punish:"
    ):

        # توافق مع أي callback قديم
        if data.startswith(
            "repetition_action:"
        ):

            await query.answer(
                "هذا الخيار لم يعد مستخدمًا.",
                show_alert=True
            )

        return

    parts = data.split(
        ":"
    )

    if len(parts) != 3:
        return

    action = parts[1]
    target_id_text = parts[2]

    if action not in (
        "mute",
        "restrict",
    ):

        return

    try:

        target_id = int(
            target_id_text
        )

    except (ValueError, TypeError):

        return

    # ==================================================
    # صلاحية من يختار العقوبة
    # ==================================================

    if not can_manage_repetition(
        actor.id,
        chat.id
    ):

        await query.answer(
            "❌ ليس لديك الصلاحية.",
            show_alert=True
        )

        return

    # ==================================================
    # تأكيد وجود الإنذارات
    # ==================================================

    try:

        warning_count = get_warning_count(
            chat.id,
            target_id
        )

    except Exception as e:

        print(
            "❌ خطأ في قراءة إنذارات المستخدم:",
            e
        )

        await query.answer(
            "❌ تعذر قراءة إنذارات المستخدم.",
            show_alert=True
        )

        return

    if warning_count < 3:

        await query.answer(
            "❌ لم يعد لديه 3 إنذارات.",
            show_alert=True
        )

        return

    # ==================================================
    # جلب المستخدم
    # ==================================================

    try:

        target = await context.bot.get_chat(
            target_id
        )

    except Exception:

        await query.answer(
            "❌ تعذر العثور على المستخدم.",
            show_alert=True
        )

        return

    # ==================================================
    # منع تطبيق العقوبة على رتبة أعلى/مساوية
    # ==================================================

    if target_id == OWNER_ID:

        await query.answer(
            "❌ لا يمكن تطبيق العقوبة على المطور الأساسي.",
            show_alert=True
        )

        return

    try:

        actor_level = get_rank_level(
            actor.id,
            chat.id
        )

        target_level = get_rank_level(
            target_id,
            chat.id
        )

    except Exception:

        actor_level = 0
        target_level = 0

    if target_level >= actor_level:

        await query.answer(
            "❌ لا يمكنك معاقبة شخص رتبته مساوية أو أعلى منك.",
            show_alert=True
        )

        return

    # ==================================================
    # مدة العقوبة
    # ==================================================

    settings = get_repetition_settings(
        chat.id
    )

    punishment_duration = settings[
        "punishment_duration"
    ]

    # ==================================================
    # تنفيذ العقوبة
    # ==================================================

    punished = await punish_user(
        update,
        context,
        target,
        action,
        punishment_duration
    )

    if not punished:

        await query.answer(
            "❌ تعذر تطبيق العقوبة.",
            show_alert=True
        )

        return

    # ==================================================
    # نجاح
    #
    # لا نمسح الإنذارات.
    # الإنذارات تبقى حتى يستخدم المشرف:
    # مسح انذاراته
    # ==================================================

    await query.answer(
        "تم اختيار العقوبة."
    )

    try:

        await query.edit_message_text(
            "• ✅ تم اختيار العقوبة المناسبة بنجاح ."
        )

    except Exception as e:

        print(
            "⚠️ خطأ في تعديل رسالة اختيار العقوبة:",
            e
        )


