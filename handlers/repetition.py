# ==================================================

def repetition_rank_allowed(
    user_id,
    chat_id,
    selected_rank
):

    if user_id == OWNER_ID:
        return False

    if is_primary_developer(
        user_id
    ):
        return False

    if selected_rank not in RANK_LEVELS:
        selected_rank = "عضو"

    try:

        level = get_rank_level(
            user_id,
            chat_id
        )

    except TypeError:

        level = get_rank_level(
            user_id
        )

    except Exception:

        return False

    selected_level = RANK_LEVELS[
        selected_rank
    ]

    return (
        level <= selected_level
    )


