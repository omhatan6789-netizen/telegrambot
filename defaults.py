def get_default_questions():

    result = []

    for word in WORDS:

        result.append({
            "game": "كلمات",
            "question": f"• اكتب كلمة ~ {word}",
            "image": None,
            "caption": None,
            "answers": [word],
        })

        result.append({
            "game": "تفكيك",
            "question": f"• فكك كلمة ~ {word}",
            "image": None,
            "caption": None,
            "answers": [" ".join(word)],
        })

    for question, answers in ANIME_QUESTIONS:

        result.append({
            "game": "انمي",
            "question": f"• {question}",
            "image": None,
            "caption": None,
            "answers": answers,
        })

    return result
